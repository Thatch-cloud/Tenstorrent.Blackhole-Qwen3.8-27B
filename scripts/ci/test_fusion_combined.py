class ContractTests(unittest.TestCase):
    def problems(self, name):
        """boot()'s checks, in its order, for a gate run of the profile."""
        profile = dict(PROFILES[name], name=name)
        environ = gate_environment(profile)
        found = []
        for check in (lambda: contract.gate_problems(profile, environ) + contract.waiver_problems(profile, environ) + contract.traffic_waiver_problems(profile),
                      lambda: contract.prefix_reuse_problems(profile), lambda: contract.levern_problems(profile), lambda: contract.multi_problems(profile),
                      lambda: contract.w2_problems(profile, environ), lambda: contract.upload_problems(profile), lambda: contract.drafter_problems(profile),
                      lambda: contract.parked_problems(profile, environ), lambda: contract.mesh_problems(profile)):
            found += check()
        return found

    def test_both_twins_pass_every_boot_check_of_the_serving_contract(self):
        for name in (TIMED, AUDITED):
            with self.subTest(profile=name):
                self.assertEqual(self.problems(name), [])

    def test_without_the_gate_switch_the_contract_refuses_them_as_gate_only(self):
        for name in (TIMED, AUDITED):
            profile = dict(PROFILES[name], name=name)
            self.assertTrue(contract.gate_problems(profile, {}), name)

    def test_the_upload_levers_are_armed_by_the_profile_and_the_environment_it_builds_carries_every_flag(self):
        for name in (TIMED, AUDITED):
            environ = gate_environment(dict(PROFILES[name], name=name))
            for key, value in additions(name).items():
                self.assertEqual(environ[key], value, (name, key))


