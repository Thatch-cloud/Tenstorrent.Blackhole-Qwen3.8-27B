class RoundHostTests(unittest.TestCase):
    """The round-host levers (tp4/round-host) beside the fusion levers: accepted together, judged by their own smoke rule, and KEYED independent of every fusion lever."""

    FLAGS = ('QWEN_FAST_TP4_ROUND_HOST_SELECT', 'QWEN_FAST_TP4_ROUND_HOST_READ', 'QWEN_FAST_TP4_ROUND_HOST_KEYED', 'QWEN_FAST_TP4_ROUND_HOST_LEAN')

    def test_the_flags_parse_strictly_beside_the_fusion_levers_and_the_audit_is_only_on_the_audited_twin(self):
        import round_host

        for name in (TIMED, AUDITED):
            environ = gate_environment(dict(PROFILES[name], name=name))
            with self.subTest(profile=name):
                state = round_host.parse(environ)
                self.assertEqual([flag for flag in round_host.FLAGS if state[flag]],
                                 [flag for flag in round_host.FLAGS if flag in self.FLAGS or (name == AUDITED and flag == round_host.AUDIT_FLAG)])
                self.assertFalse(state[round_host.LOG_FLAG], 'the ledger comes from LEAN')
                self.assertTrue(round_host.requested(environ))
        base = gate_environment(dict(PROFILES[TIMED], name=TIMED))
        for flag in self.FLAGS:
            base.pop(flag)
        base['QWEN_FAST_TP4_ROUND_HOST_AUDIT'] = '1'
        with self.assertRaises(ValueError, msg='an audit with no lever is refused: the check is live'):
            round_host.parse(base)

    def test_the_smoke_rule_of_the_round_host_judges_both_twins_by_their_own_flags(self):
        import round_host

        for name in (TIMED, AUDITED):
            env = PROFILES[name]['env']
            problems, _facts = c2_smoke_check.round_host_problems(env, '', False)
            self.assertTrue(any('round host' in problem and 'one needed' in problem for problem in problems), name)
            engaged = '%s %s' % (round_host.ENGAGED_MARKER, ' '.join('%s=%d' % (flag.rsplit('_', 1)[-1].lower(), int(env.get(flag) == '1')) for flag in round_host.FLAGS))
            right, _facts = c2_smoke_check.round_host_problems(env, engaged + '\n', False)
            self.assertFalse([problem for problem in right if 'the engaged line says' in problem], name)
            wrong, _facts = c2_smoke_check.round_host_problems(env, engaged.replace('keyed=1', 'keyed=0') + '\n', False)
            self.assertTrue([problem for problem in wrong if 'keyed=0' in problem], name)

    def test_the_keyed_values_and_the_pre_stage_name_no_fusion_lever(self):
        """KEYED's claim is that every staged value but the tokens is a pure function of (start, page table) per segment. The staged list is packed_values and the pre-stage
        snapshot is verify_prestage; neither reads a fusion lever's flag, so no lever can change a staged value (a lever that did would make the keyed round write stale bytes)."""
        import ast

        flags = set(flag for flag, _value, _engaged, _fell, _what in c2_smoke_check.FUSION_LEVERS) | set(flag + '_AUDIT' for flag, *_rest in c2_smoke_check.FUSION_LEVERS)
        flags |= set(row[0] for row in c2_smoke_check.SAMPDRAFT_LEVERS) | set(row[0] for row in c2_smoke_check.SAMPDRAFT_AUDITS)
        flags |= {'QWEN_FAST_TP4_SHARD_ARGMAX_FOLD2', 'QWEN_FAST_DEVICE_ZEROS', 'QWEN_FAST_LAZY_SHARD_W'}
        self.assertIn('QWEN_FAST_KV_PAGE_WRITER', flags)
        prestage = (HERE / 'verify_prestage.py').read_text(encoding='utf-8')
        self.assertEqual([flag for flag in sorted(flags) if flag in prestage], [])
        tree = ast.parse((HERE / 'packed_verifier.py').read_text(encoding='utf-8'))
        function = next(node for node in tree.body if isinstance(node, ast.FunctionDef) and node.name == 'packed_values')
        constants = {node.value for node in ast.walk(function) if isinstance(node, ast.Constant) and isinstance(node.value, str)}
        self.assertEqual(sorted(flags & constants), [])
        names = {node.id for node in ast.walk(function) if isinstance(node, ast.Name)}
        self.assertFalse(names & {'kv_page_writer_tp4', 'draft_fusion_tp', 'tp4_mlp_gateup', 'tp4_shard_argmax', 'ccl_options_tp'})
        keyed = (HERE / 'verify_prestage.py').read_text(encoding='utf-8')
        self.assertIn("__slots__ = ('starts', 'tables', 'readers', 'token_index', 'kv_ok')", keyed)


class SmokeTableTests(unittest.TestCase):
    def rows(self):
        levers = [(flag, value) for flag, value, _engaged, _fell, _what in c2_smoke_check.FUSION_LEVERS]
        levers += [(flag, '1') for flag, *_rest in c2_smoke_check.SAMPDRAFT_LEVERS]
        audits = [flag for flag, _marker, _what in c2_smoke_check.FUSION_AUDITS] + [flag for flag, _marker, _what in c2_smoke_check.SAMPDRAFT_AUDITS]
        return levers, audits

    def test_every_lever_flag_of_the_twins_has_a_smoke_row_at_the_value_it_carries(self):
        levers, audits = self.rows()
        env = PROFILES[AUDITED]['env']
        companions = ('QWEN_FAST_TP4_SHARD_ARGMAX_FOLD2', 'QWEN_FAST_DEVICE_ZEROS', 'QWEN_FAST_LAZY_SHARD_W')     # (judged by their packages' own rules, not the generic tables)
        for flag, value in SWITCHED_ON.items():
            if flag in companions or flag.startswith('QWEN_FAST_TP4_ROUND_HOST_'):      # (the round-host levers: c2_smoke_check.round_host_problems)
                continue
            self.assertIn((flag, value), levers, 'no smoke row judges %s=%s' % (flag, value))
        for flag in AUDIT_FLAGS:
            if flag in ('QWEN_FAST_DEVICE_ZEROS_AUDIT', 'QWEN_FAST_LAZY_SHARD_W_AUDIT', 'QWEN_FAST_TP4_ROUND_HOST_AUDIT'):
                continue
            self.assertIn(flag, audits, 'no smoke row demands an exact=True line for ' + flag)
            self.assertEqual(env[flag], '1')

    def test_the_upload_levers_are_judged_by_the_contract_s_own_smoke_rule(self):
        # (c2_smoke_check.upload_p0_problems reads DEVICE_ZEROS / LAZY_SHARD_W and their audits)
        env = dict(PROFILES[AUDITED]['env'])
        problems = c2_smoke_check.upload_p0_problems(env, '')
        self.assertTrue(any('QWEN_FAST_DEVICE_ZEROS' in problem for problem in problems))
        self.assertTrue(any('QWEN_FAST_LAZY_SHARD_W' in problem for problem in problems))

    def test_a_log_without_any_lever_fails_the_audited_twin_lever_by_lever(self):
        env = PROFILES[AUDITED]['env']
        found = c2_smoke_check.fusion_problems('nothing\n', env)
        for flag in ('QWEN_FAST_DRAFT_PERMUTE', 'QWEN_FAST_DRAFT_REDUCE', 'QWEN_FAST_DRAFT_QKV1', 'QWEN_FAST_DRAFT_TAIL', 'QWEN_FAST_DRAFT_GATEUP1', 'QWEN_FAST_DRAFT_MM_GRID',
                     'QWEN_FAST_DRAFT_HEAD64', 'QWEN_FAST_CCL_OPTIONS', 'QWEN_FAST_MLP_CFG'):
            self.assertTrue(any(flag in problem for problem in found), flag)
        self.assertTrue(any('QWEN_FAST_TP4_SHARD_ARGMAX' in problem for problem in c2_smoke_check.sampdraft_problems('nothing\n', env)))


class ParkedEngineBandTests(unittest.TestCase):
    """The parked-engine DRAM band (parked_judge.ENGINE_GB) is lever-aware for the op-fusion arms and exactly as before for everything else."""

    @staticmethod
    def ledger(each, free_after=4.0, engines=8):
        def line(phase, chip, allocated, free):
            return '[MEMLEDGER] phase=%s point=x chip%d allocated=%.3fGB free=%.3fGB largest_free=%.1fMB total=33.0GB' % (phase, chip, allocated, free, free * 900)
        return '\n'.join([line('P7', chip, 24.78, 8.87) for chip in range(4)] + [line('P7p', chip, 24.78 + engines * each, free_after) for chip in range(4)]) + '\n'

    @staticmethod
    def took(env, text):
        return [problem for problem in c2_smoke_check.parked_container_problems(env, text)[0] if 'parked engines took' in problem]

    def test_only_the_fusion_arms_get_the_lever_band_and_production_keeps_its_own(self):
        import parked_judge

        for name, profile in PROFILES.items():
            if profile['env'].get('QWEN_FAST_PARKED_ENGINES') != '1':
                continue                    # the band is only judged for an arm that parks engines (the older S1 profiles never do)
            levers, audits = c2_smoke_check.fusion_arm_flags(profile['env'])
            band = parked_judge.engine_band(levers, audits)
            twin = name.startswith(fusion.NAMESPACE) or name in fusion.twin_names()
            with self.subTest(profile=name):
                if not twin:
                    self.assertEqual((levers, audits, band), ([], [], parked_judge.ENGINE_GB))
                else:
                    self.assertNotEqual(band, parked_judge.ENGINE_GB)
        self.assertEqual(parked_judge.ENGINE_GB, (0.46, 0.51))
        self.assertEqual(c2_smoke_check.fusion_arm_flags(None), ([], []))
        self.assertEqual(c2_smoke_check.fusion_arm_flags(dict(PARENT['env'], QWEN_FAST_DRAFT_REDUCE='0')), ([], []))

    def test_the_measured_combined_arm_passes_and_the_same_reading_still_fails_production(self):
        # run v714 and v716: 3.346 GB for eight engines on every chip (0.418 each) failed the production band 3.68-4.08 and is the lever arm's measurement
        reading = self.ledger(3.346 / 8)
        self.assertEqual(self.took(PROFILES[TIMED]['env'], reading), [])
        failed = self.took(PARENT['env'], reading)
        self.assertEqual(len(failed), 4)
        self.assertTrue(all('3.346' in problem and '3.68-4.08' in problem for problem in failed))

    def test_the_lever_arm_keeps_the_production_ceiling_and_has_a_floor(self):
        env = PROFILES[TIMED]['env']
        self.assertEqual(self.took(env, self.ledger(0.495)), [])                      # the production engine is within the lever band
        self.assertEqual(len(self.took(env, self.ledger(0.52))), 4)                   # a lever that ADDS DRAM is not absorbed
        self.assertEqual(len(self.took(env, self.ledger(0.37))), 4)                   # an engine that is not the whole captured graph is not either
        self.assertTrue(any('op-fusion lever arm' in problem for problem in self.took(env, self.ledger(0.52))))
        self.assertEqual(self.took(PARENT['env'], self.ledger(0.48)), [])
        self.assertEqual(len(self.took(PARENT['env'], self.ledger(0.418))), 4)

    def test_a_single_lever_twin_lies_between_the_production_engine_and_the_whole_set(self):
        for name in fusion.twin_names():
            if name in (TIMED, AUDITED) or name.endswith('-audit'):
                continue
            env = PROFILES[name]['env']
            if not c2_smoke_check.fusion_arm_flags(env)[0]:
                continue
            with self.subTest(profile=name):
                self.assertEqual(self.took(env, self.ledger(0.418)), [])
                self.assertEqual(self.took(env, self.ledger(0.48)), [])

    def test_an_audited_lever_arm_has_no_ceiling_but_the_free_dram_floor_binds(self):
        env = PROFILES[AUDITED]['env']
        self.assertEqual(self.took(env, self.ledger(0.8, free_after=3.7)), [])
        self.assertEqual(len(self.took(env, self.ledger(0.37, free_after=3.7))), 4)
        floor = [problem for problem in c2_smoke_check.parked_container_problems(env, self.ledger(0.8, free_after=3.0))[0] if 'floor' in problem]
        self.assertEqual(len(floor), 4)
        facts = c2_smoke_check.parked_container_problems(env, self.ledger(0.8, free_after=3.7))[1]
        self.assertEqual(facts['engine_gb'], {0: 0.8, 1: 0.8, 2: 0.8, 3: 0.8})        # the first completed audited run prints the figure that sets its ceiling


