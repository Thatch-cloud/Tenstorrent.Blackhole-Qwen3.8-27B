"""The op-fusion programme's COMBINED twins (docs/tp4-fusion.md): `...-w2-er-fx-all` (every lever that is exact by construction on together) and `...-fx-all-audit` (plus every
lever's _AUDIT flag), generated by make_fusion_profiles.py from the combined entry of fusion-wp/WP0.json.

Held, for both twins:
  - the twin is the production profile plus exactly the levers' flags (and nothing of the two levers that wait for a card: the K/V page writer, the fused MLP gate|up);
  - the profile passes serving_c2_contract's boot checks as a gate run (every check boot() makes before it touches the environment), and the environment it builds is accepted by
    every package's strict validator at once: the shard-argmax pair with its tree fold, the drafter levers, the CCL options (whose reduce-scatter tokens need the unit-major lever the
    parent carries), the MLP configuration, the engine-start upload levers, the sampdraft pairing;
  - every flag of the twin has a row in the smoke tables (the generated ones or the static ones) at the value it carries, so a boot that runs the combination is judged lever by lever;
  - the audited twin differs from the timed twin by the audit flags and nothing else;
  - the combined card pack (references/fusion-jobs/combined) is the audited attach and the timed ABAB of exactly these two twins, and every template exits zero through the job reader.

    py -3.11 -B -m unittest test_fusion_combined      (from scripts/ci)
"""

