"""The tp4/sched-2 gate-only twins of the ship-5 candidate: the admission levers of docs/tp4-sched2.md, generated from the files they are made of (stdlib only).

    python3 scripts/ci/make_sched2_profiles.py --write   regenerate the twins in scripts/ci/qwen_c2_profiles.json
    python3 scripts/ci/make_sched2_profiles.py --check   exit 1 if the checked-in twins are not what their parents generate

NEVER hand-merge these entries into the profiles file. Run make_fusion_profiles.py --write FIRST (it writes the ship-5 candidate, `-fx-traffic-s5`), then make_octo3_profiles.py,
make_ship4_profiles.py, make_np1_profiles.py, make_xe_profiles.py, make_pf2_profiles.py and make_s5_profiles.py (the audited twin of ship 5 is the audited arm's parent), then this.
The twins sit right after the ship-5 twins.

WHAT THEY SERVE. At ship 5 a returning turn's first token waits for its engine to be bound (275 ms at p50) and the scheduler's DRAM hold reads the allocator (84 ms) before every
arrival; the first rebind of each slot also pays the memory ledger's bracket and the first adoption of each native slot the conv-slice readback (the cold 8-user burst pays all eight).
Three levers, each default off and each in a timed arm of its own so that the card ABAB names which moved what, one arm with all of them, one audited arm:

  -sch-s5-seed    THE PIPELINING ARM: the ship-5 candidate + QWEN_FAST_ADMISSION_SEED_FIRST=1 (the seed token leaves the engine before the bind; a schedule() wrapper binds first)
  -sch-s5-hold    THE HOLD ARM:       + QWEN_FAST_ADMISSION_HOLD_REUSE=1 (the DRAM hold reuses a recent allocator reading while it clears the terms)
  -sch-s5-ledger  THE LEDGER ARM:     + QWEN_FAST_ADMISSION_LEDGER_TRIM=1 (the memory ledger ends after the attach)
  -sch-s5-all     the three together (the timed arm of the combined ABAB)
  -sch-s5-audit   THE AUDITED ATTACH ARM: the ship-5 audited twin (-fx-s5-audit: every audit of the candidate) + seed first + hold reuse. Not the ledger trim: the audit's judge reads the
                   ledger's points, which the trim removes.

The timed arms are the candidate with the gate marker (QWEN_C2_GATE_PROFILE=1) in place of its owner waiver id, as the sched-1 arms are, and gate_only; nothing about the engine,
the memory plan or any other flag differs from the parent. The ship-5 candidate is NOT changed.
"""

import argparse
import copy
import json
from pathlib import Path
import sys

import make_octo_profiles
import make_s5_profiles as s5

PROFILES = Path(__file__).resolve().parent / 'qwen_c2_profiles.json'

# (Not under make_fusion_profiles.NAMESPACE, whose --write drops every name under it that it does not own; the sched-1 twins are named the same way, `-w2-er-sch-`.)
NAMESPACE = 'c2-packed-tp4-8x262k-ship-prefix-levern-w2-er-sch-s5-'
SHIP = s5.SHIP                              # the ship-5 candidate: the control of every pair
AUDIT_PARENT = s5.AUDIT                     # the ship-5 audited twin
WAIVER_ENV = s5.WAIVER_ENV
WAIVER_FIELD = s5.WAIVER_FIELD
MARKER_ENV = dict(make_octo_profiles.MARKER_ENV)

SEED = {'QWEN_FAST_ADMISSION_SEED_FIRST': '1'}
HOLD = {'QWEN_FAST_ADMISSION_HOLD_REUSE': '1'}
LEDGER = {'QWEN_FAST_ADMISSION_LEDGER_TRIM': '1'}
ALL = dict(SEED, **dict(HOLD, **LEDGER))
AUDITED = dict(SEED, **HOLD)
# (suffix, flags, parent: 'ship' | 'audit', what it is)
ARMS = (('seed', SEED, 'ship', 'THE PIPELINING ARM'), ('hold', HOLD, 'ship', 'THE HOLD ARM'), ('ledger', LEDGER, 'ship', 'THE LEDGER ARM'),
        ('all', ALL, 'ship', 'THE COMBINED TIMED ARM'), ('audit', AUDITED, 'audit', 'THE AUDITED ATTACH ARM'))
NAMES = tuple(NAMESPACE + suffix for suffix, _flags, _parent, _what in ARMS)
FLAGS = tuple(sorted(ALL))
NEEDED = ('QWEN_FAST_LEVER_N', 'QWEN_PREFIX_REUSE', 'QWEN_FAST_ADMISSION_LEAN', 'QWEN_FAST_EXTENT_REPLAY', 'QWEN_FAST_PARKED_ENGINES', 'QWEN_FAST_ANY_REQUEST')


def name_of(suffix):
    return NAMESPACE + suffix


def describe(suffix, flags, parent, what):
    parent_name = SHIP if parent == 'ship' else AUDIT_PARENT
    adds = ', '.join('%s=%s' % pair for pair in sorted(flags.items()))
    if parent == 'ship':
        marker = ('the gate marker %s instead of its owner waiver id %s (the gate run admits the octo shape, as the sched-1 arms do) and gate_only'
                  % (', '.join('%s=%s' % pair for pair in sorted(MARKER_ENV.items())), WAIVER_ENV))
    else:
        marker = 'nothing else (the parent is already a gate-only profile with every audit on)'
    return ('GATE ONLY, UNQUALIFIED (tp4/sched-2, docs/tp4-sched2.md; never traffic). %s of the admission levers. The parent is %s and this profile is that parent plus exactly %s and %s; its '
            'engine, memory plan and every other flag are the parent\'s byte for byte. %s Generated by scripts/ci/make_sched2_profiles.py: regenerate, never hand-merge.'
            % (what, parent_name, adds, marker,
               'The paired jobs of references/fusion-jobs/SCH2 time it against the ship-5 candidate.' if parent == 'ship'
               else 'Every audit of the candidate runs beside the seed-first bind and the hold\'s reading reuse; the read is the ship-5 audited attach\'s, with the lines of the two levers present.'))


def specs():
    """[(profile name, parent name, what it is)] in the order they are written."""
    return [(name_of(suffix), SHIP if parent == 'ship' else AUDIT_PARENT, describe(suffix, flags, parent, what)) for suffix, flags, parent, what in ARMS]


def twin_names():
    """The generated twins' names (the profile-enumerating tests exempt them through profile_twins; test_sched2_profiles holds each)."""
    return NAMES


def parent_problems(name, profile, audit):
    """Why `name` cannot be twinned, [] when it can."""
    problems = []
    env = profile.get('env') or {}
    for flag in FLAGS:
        if flag in env:
            problems.append('%s already names %s: a parent never carries the knob it is twinned with' % (name, flag))
    if audit:
        if profile.get('gate_only') is not True or env.get('QWEN_C2_GATE_PROFILE') != '1':
            problems.append('%s is not the gate-only audited twin of the ship-5 candidate' % name)
    else:
        waiver = profile.get(WAIVER_FIELD)
        if profile.get('gate_only') is True or not isinstance(waiver, dict):
            problems.append('%s is not a traffic profile with an owner traffic waiver: the arm is that profile with the gate marker in its place' % name)
        elif env.get(WAIVER_ENV) != waiver.get('id'):
            problems.append('%s does not carry its waiver id in %s' % (name, WAIVER_ENV))
        for flag in MARKER_ENV:
            if flag in env:
                problems.append('%s already names %s: a traffic profile never carries the gate marker' % (name, flag))
    for needed in NEEDED:
        if env.get(needed) != '1':
            problems.append('%s does not set %s=1, which the levers need' % (name, needed))
    return problems


def generate(data):
    """data's profiles with the twins inserted right after the ship-5 twins (every other entry unmoved); returns the new dict."""
    profiles = data['profiles']
    for name in (AUDIT_PARENT, SHIP):
        if name not in profiles:
            raise ValueError('the parent profile %s is not defined (make_fusion_profiles.py --write ... make_s5_profiles.py --write, first)' % name)
    problems = parent_problems(AUDIT_PARENT, profiles[AUDIT_PARENT], True) + parent_problems(SHIP, profiles[SHIP], False)
    if problems:
        raise ValueError('; '.join(problems))
    generated = {}
    for suffix, flags, parent, what in ARMS:
        if parent == 'ship':
            arm = copy.deepcopy(profiles[SHIP])
            arm['env'].pop(WAIVER_ENV)
            arm['env'].update(MARKER_ENV)
            arm.pop(WAIVER_FIELD, None)
        else:
            arm = copy.deepcopy(profiles[AUDIT_PARENT])
        arm['env'].update(flags)
        arm['description'] = describe(suffix, flags, parent, what)
        arm.pop('gate_only', None)
        arm['gate_only'] = True
        generated[name_of(suffix)] = arm
    remaining = [name for name in profiles if name not in generated]            # a previous generation is replaced below
    anchors = [name for name in remaining if name in s5.twin_names()]
    if not anchors:
        raise ValueError('the tp4/next-1 ship-5 twins are not in the profiles file (make_s5_profiles.py --write first)')
    anchor = anchors[-1]
    result = {}
    for name in remaining:
        result[name] = profiles[name]
        if name == anchor:
            result.update(generated)
    out = dict(data)
    out['profiles'] = result
    return out


def render(data):
    return json.dumps(data, indent=2) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--path', default=str(PROFILES))
    arguments = parser.parse_args(argv)
    path = Path(arguments.path)
    current = path.read_text(encoding='utf-8')
    wanted = render(generate(json.loads(current)))
    if arguments.check:
        if wanted != current:
            sys.stderr.write('%s is not what make_sched2_profiles.py generates from its parents: run it with --write\n' % path)
            return 1
        return 0
    if arguments.write:
        if wanted != current:
            with open(str(path), 'w', encoding='utf-8', newline='\n') as handle:
                handle.write(wanted)
        return 0
    parser.error('--write or --check')


if __name__ == '__main__':
    sys.exit(main())
