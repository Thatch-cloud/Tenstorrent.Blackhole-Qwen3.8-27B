"""The tp4/sampled-verify gate-only profiles: the ship-7 stack with sampled verification on (docs/tp4-sampled-verify.md), generated from the files they are made of (stdlib only).

    python3 scripts/ci/make_sampled_profiles.py --write   regenerate the profiles in scripts/ci/qwen_c2_profiles.json
    python3 scripts/ci/make_sampled_profiles.py --check   exit 1 if the checked-in profiles are not what their parents generate

NEVER hand-merge these entries into the profiles file. Run make_fusion_profiles.py --write FIRST (it writes the ship-7 candidate, `-fx-traffic-s7`, from scripts/ci/fusion-wp/S7.json), then
the generators of the tp4/s7 chain (make_octo3_profiles.py ... make_s7_profiles.py, which writes the audited twin `-fx-s7-audit`), then this. The profiles sit right after the ship-7 audited
twin. They are NOT under make_fusion_profiles.NAMESPACE (whose --write drops every name under it that it does not own).

  -smp-s7        THE SAMPLED ARM: the ship-7 candidate (a traffic profile with its owner traffic waiver) with the gate marker (QWEN_C2_GATE_PROFILE=1) in place of the waiver id, gate_only, and
                 QWEN_FAST_SAMPLED=1. Nothing else differs: its engine, memory plan and every other flag are the candidate's, so a timed pair against the candidate (greedy) and a text gate
                 against the plain sampler measure only what sampling costs and gives.
  -smp-s7-audit  THE AUDITED ARM: the ship-7 audited twin (`-fx-s7-audit`: every audit of the candidate) with QWEN_FAST_SAMPLED=1 and QWEN_FAST_SAMPLED_AUDIT=1 (the audited rounds read the logits
                 back and compare the device slice and the draw with the reference path's).

Both are gate_only and unqualified. No profile that ships names the switch, and neither replaces one: the ship-7 candidate and its twins are untouched.
"""

import argparse
import copy
import json
from pathlib import Path
import sys

import make_octo_profiles
import make_s5_profiles as s5
import make_s7_profiles as s7

PROFILES = Path(__file__).resolve().parent / 'qwen_c2_profiles.json'

# (Not under make_fusion_profiles.NAMESPACE, whose --write drops every name under it that it does not own.)
BASE = 'c2-packed-tp4-8x262k-ship-prefix-levern-w2-er-'
TIMED = BASE + 'smp-s7'
AUDIT = BASE + 'smp-s7-audit'
NAMES = (TIMED, AUDIT)
SHIP = s7.SHIP                              # the ship-7 candidate (generated by make_fusion_profiles.py from fusion-wp/S7.json): the control of the pair
AUDIT_PARENT = s7.AUDIT                     # the ship-7 audited twin
WAIVER_ENV = s5.WAIVER_ENV
WAIVER_FIELD = s5.WAIVER_FIELD
MARKER_ENV = dict(make_octo_profiles.MARKER_ENV)
SWITCH = 'QWEN_FAST_SAMPLED'
AUDIT_SWITCH = 'QWEN_FAST_SAMPLED_AUDIT'
TIMED_FLAGS = {SWITCH: '1'}
AUDIT_FLAGS = {SWITCH: '1', AUDIT_SWITCH: '1'}
MAX_NAME = 64
NEEDED = ('QWEN_FAST_ANY_REQUEST', 'QWEN_FAST_TP')


def describe(name):
    if name == TIMED:
        return ('GATE ONLY, UNQUALIFIED (tp4/sampled-verify, docs/tp4-sampled-verify.md; never traffic). THE SAMPLED ARM of the ship-7 candidate %s: sampling on the fast path. The parent is %s and this '
                'profile is that parent plus exactly %s and the gate marker %s instead of its owner waiver id %s, and gate_only; its engine, memory plan and every other flag are the parent\'s byte for '
                'byte. A request with a temperature is served: each chip returns its vocabulary shard\'s top-64 through stock ttnn.topk beside the shard argmax (which still serves every greedy '
                'request), the host merges, filters (temperature, top_k, top_p) and draws with SplitMix64 noise keyed only by (the request\'s seed, the absolute position of the token), the first '
                'token included, so the committed text equals plain one-token-at-a-time sampling with the same seed. Generated by scripts/ci/make_sampled_profiles.py: regenerate, never hand-merge.'
                % (SHIP, SHIP, ', '.join('%s=%s' % pair for pair in sorted(TIMED_FLAGS.items())), ', '.join('%s=%s' % pair for pair in sorted(MARKER_ENV.items())), WAIVER_ENV))
    return ('GATE ONLY, UNQUALIFIED (tp4/sampled-verify, docs/tp4-sampled-verify.md; never traffic, never a timed arm). THE AUDITED SAMPLED ARM. The parent is %s, the ship-7 audited twin (every audit of '
            'the candidate), and this profile is that parent plus exactly %s: the audited rounds (QWEN_FAST_AUDIT_FIRST/EVERY) read the sampled rows\' logits back whole and compare the device '
            'top-64 slice and the draw with the reference path\'s (sampled_accept.topk_slice and draw_batch, the functions the gold decode calls), and every sampled round compares the slice\'s first '
            'candidate with the shard argmax. Generated by scripts/ci/make_sampled_profiles.py: regenerate, never hand-merge.'
            % (AUDIT_PARENT, ', '.join('%s=%s' % pair for pair in sorted(AUDIT_FLAGS.items()))))


def specs():
    """[(profile name, parent name, description)] in the order they are written."""
    return [(TIMED, SHIP, describe(TIMED)), (AUDIT, AUDIT_PARENT, describe(AUDIT))]


def twin_names():
    """The generated profiles' names (the profile-enumerating tests exempt them through profile_twins; test_sampled_profiles holds them)."""
    return NAMES


def owned_names():
    """The names the census tests that exempt the generated families read, as make_s7_profiles.owned_names does: here the twins alone (both are gate-only; the ship-7 candidate they derive from is the s7 generator's)."""
    return NAMES


def parent_problems(profiles):
    """Why the profiles cannot be generated, [] when they can."""
    problems = []
    for name in (SHIP, AUDIT_PARENT):
        if name not in profiles:
            problems.append('the parent profile %s is not defined (make_fusion_profiles.py --write, then make_s7_profiles.py --write first)' % name)
    problems += ['%s is %d characters, over the %d a profile name may have' % (name, len(name), MAX_NAME) for name in NAMES if len(name) > MAX_NAME]
    if problems:
        return problems
    for name in (SHIP, AUDIT_PARENT):
        env = profiles[name].get('env') or {}
        for flag in (SWITCH, AUDIT_SWITCH):
            if flag in env:
                problems.append('%s already names %s: a parent never carries the knob it is twinned with' % (name, flag))
        for needed in NEEDED:
            if not env.get(needed):
                problems.append('%s does not set %s, which the sampled path needs' % (name, needed))
    audit = profiles[AUDIT_PARENT]
    if audit.get('gate_only') is not True or (audit.get('env') or {}).get('QWEN_C2_GATE_PROFILE') != '1':
        problems.append('%s is not the gate-only audited twin of ship 7' % AUDIT_PARENT)
    ship = profiles[SHIP]
    waiver = ship.get(WAIVER_FIELD)
    if ship.get('gate_only') is True or not isinstance(waiver, dict):
        problems.append('%s is not a traffic profile with an owner traffic waiver: the arm is that profile with the gate marker in its place' % SHIP)
    elif (ship.get('env') or {}).get(WAIVER_ENV) != waiver.get('id'):
        problems.append('%s does not carry its waiver id in %s' % (SHIP, WAIVER_ENV))
    for flag in MARKER_ENV:
        if flag in (ship.get('env') or {}):
            problems.append('%s already names %s: a traffic profile never carries the gate marker' % (SHIP, flag))
    return problems


def generate(data):
    """data's profiles with the two profiles inserted right after the ship-7 audited twin (every other entry unmoved); returns the new dict."""
    profiles = data['profiles']
    problems = parent_problems(profiles)
    if problems:
        raise ValueError('; '.join(problems))
    generated = {}
    for name, parent, description in specs():
        if parent == SHIP:
            arm = copy.deepcopy(profiles[SHIP])
            arm['env'].pop(WAIVER_ENV)
            arm['env'].update(MARKER_ENV)
            arm.pop(WAIVER_FIELD, None)
            arm['env'].update(TIMED_FLAGS)
        else:
            arm = copy.deepcopy(profiles[AUDIT_PARENT])
            arm['env'].update(AUDIT_FLAGS)
        arm['description'] = description
        arm.pop('gate_only', None)
        arm['gate_only'] = True
        generated[name] = arm
    remaining = [name for name in profiles if name not in generated]            # a previous generation is replaced below
    anchor = s7.AUDIT
    if anchor not in remaining:
        raise ValueError('the ship-7 audited twin %s is not in the profiles file (make_s7_profiles.py --write first)' % anchor)
    result = {}
    for name in remaining:
        result[name] = profiles[name]
        if name == anchor:
            result.update(generated)
    out = dict(data)
    out['profiles'] = result
    return out


def render(data):
    return json.dumps(data, indent=2) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--path', default=str(PROFILES))
    arguments = parser.parse_args(argv)
    path = Path(arguments.path)
    current = path.read_text(encoding='utf-8')
    wanted = render(generate(json.loads(current)))
    if arguments.check:
        if wanted != current:
            sys.stderr.write('%s is not what make_sampled_profiles.py generates from its parents: run it with --write\n' % path)
            return 1
        return 0
    if arguments.write:
        if wanted != current:
            with open(str(path), 'w', encoding='utf-8', newline='\n') as handle:
                handle.write(wanted)
        return 0
    parser.error('--write or --check')


if __name__ == '__main__':
    sys.exit(main())
