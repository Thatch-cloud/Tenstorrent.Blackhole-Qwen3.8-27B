"""The tp4/next-1 gate-only twin of the ship-5 candidate, generated from the files it is made of (stdlib only).

    python3 scripts/ci/make_s5_profiles.py --write   regenerate the twin in scripts/ci/qwen_c2_profiles.json
    python3 scripts/ci/make_s5_profiles.py --check   exit 1 if the checked-in twin is not what its parents generate

NEVER hand-merge this entry into the profiles file. Run make_fusion_profiles.py --write FIRST (it writes the ship-5 candidate, `-fx-traffic-s5`, from scripts/ci/fusion-wp/S5.json), then
make_octo3_profiles.py and make_ship4_profiles.py (the audited twin of ship 4 is this twin's parent), make_np1_profiles.py and make_xe_profiles.py (this one is placed after the last), then this.

THE CANDIDATE is the traffic profile `-fx-traffic-s5` (docs/tp4-next1.md): the approved ship-4 profile plus the lone-user padded round (NP1), exact resume P0, the sliced host-tier restore, the decode verify
sub-switch of the 13x10 grids and the owner-approved host RAM budget (a 48 GiB tier beside a 16 GiB checkpoint store), under ONE owner traffic waiver whose decision is PENDING. Its gate-only twins:

  -fx-s5-audit  THE AUDITED ATTACH ARM: the ship-4 audited twin (`-fx-s4-audit`: every audit of the shipped stack, the host tier with every instrument on, the verify sub-switch of the grids) plus every
                difference of the candidate from ship 4 (the candidate's own env, read from the two profiles so that it cannot drift) plus the instruments of what the candidate adds
                (QWEN_PREFIX_WINDOW_CARRY_AUDIT) plus the one lever it does NOT carry, W3 WC (QWEN_FAST_TP4_GDN_WC with its audit): the audited run is the lever's first, and a lever that is wrong
                costs one audited attach, not a candidate. F1's audit (QWEN_FAST_TP4_CONV_GATES_SPREAD_AUDIT) is taken out because gdn_wc refuses it beside WC (a layer WC serves never calls F1's
                launch; WC's own audit holds those layers instead, and F1 stays the launch for a layer WC declines, the octo block's among them).

  -fx-s5-audit-nowc  THE FALLBACK: the audited twin without W3 WC (QWEN_FAST_TP4_GDN_WC and its audit), with F1's audit back. WC's two kernels have never been through a compiler, so the first audited attach may stop
                at their first JIT compile; that is a fault of an UNSHIPPED lever and no reason to lose the audit of the rest of the candidate, which this twin carries whole.

There is no gate-only TIMED twin: the candidate is a traffic profile whose waiver decision is PENDING, and a profile whose decision does not start with APPROVED boots in a gate or a smoke and logs the
word (only a build refuses to bake it), so the timed arm of every pair is the candidate itself, as the ship-4 candidate's was. The twin is gate_only and unqualified.
"""

import argparse
import copy
import json
from pathlib import Path
import sys

import make_xe_profiles as xe
import make_ship4_profiles as ship4

PROFILES = Path(__file__).resolve().parent / 'qwen_c2_profiles.json'

NAMESPACE = ship4.NAMESPACE
SHIP4 = ship4.SHIP                                  # the approved ship-4 profile: the control of every pair
SHIP = NAMESPACE + 'traffic-s5'                     # the candidate (generated by make_fusion_profiles.py from fusion-wp/S5.json)
AUDIT_PARENT = ship4.AUDIT                          # the ship-4 audited twin
AUDIT = NAMESPACE + 's5-audit'
AUDIT_NOWC = NAMESPACE + 's5-audit-nowc'
WAIVER_ENV = ship4.WAIVER_ENV
WAIVER_FIELD = ship4.WAIVER_FIELD
# What the audited twin adds that the candidate does not carry: the carry's audit and W3 WC with its audit.
AUDIT_ADDS = {'QWEN_PREFIX_WINDOW_CARRY_AUDIT': '1', 'QWEN_FAST_TP4_GDN_WC': '1', 'QWEN_FAST_TP4_GDN_WC_AUDIT': '1'}
# What the audited twin takes out: gdn_wc.enabled() refuses F1's audit beside WC.
AUDIT_REMOVES = ('QWEN_FAST_TP4_CONV_GATES_SPREAD_AUDIT',)
WC_FLAGS = ('QWEN_FAST_TP4_GDN_WC', 'QWEN_FAST_TP4_GDN_WC_AUDIT')
NAMES = (AUDIT, AUDIT_NOWC)


def candidate_changes(profiles):
    """{flag: value} the candidate sets that ship 4 does not (or sets differently), the waiver id aside: read from the two profiles."""
    old, new = profiles[SHIP4]['env'], profiles[SHIP]['env']
    return dict((flag, value) for flag, value in sorted(new.items()) if old.get(flag) != value and flag != WAIVER_ENV)


def audit_description(changes=None):
    shown = ', '.join('%s=%s' % pair for pair in sorted((changes or {}).items()))
    return ('GATE ONLY, UNQUALIFIED (tp4/next-1, docs/tp4-next1.md; never traffic, never a timed arm). THE AUDITED ATTACH ARM of the ship-5 candidate %s. The parent is %s, the ship-4 audited twin (every '
            'audit of the shipped stack, the host KV tier at its production size with every instrument on, the 13x10 grids with all three sub-switches), and this profile is that parent plus exactly '
            'every difference of the candidate from ship 4 (%s), plus the carry\'s audit and W3 WC with its audit (%s), less F1\'s audit (%s, which gdn_wc refuses beside WC), without an owner traffic '
            'waiver. So every audit of the shipped levers runs beside the lone-user padded round (NP1: the K/V page writer, the T2 guard and the pre-stage audits on the rounds whose third idle segment '
            'writes the scratch page), exact resume (the undrop and the drafter-window carry, the carried rows read back and every sticky window\'s digest logged), the sliced restore (verify=all and the '
            'read-back audit on every slice) and W3 WC (the one-launch windows, conv and gates held against the served per-user path on every audited layer of every M3 block; the octo block is not a WC '
            'block). Generated by scripts/ci/make_s5_profiles.py: regenerate, never hand-merge.'
            % (SHIP, AUDIT_PARENT, shown or 'see the candidate', ', '.join('%s=%s' % pair for pair in sorted(AUDIT_ADDS.items())), ', '.join(AUDIT_REMOVES)))


def nowc_description():
    return ('GATE ONLY, UNQUALIFIED (tp4/next-1, docs/tp4-next1.md; never traffic, never a timed arm). THE FALLBACK of the audited attach of the ship-5 candidate %s: the audited twin %s without W3 WC (%s) and with '
            'F1\'s audit (%s) back, i.e. the ship-4 audited twin %s plus every difference of the candidate from ship 4 and the carry\'s audit, and nothing of the one lever the candidate does not carry. WC\'s kernels '
            'have never been compiled: when the first attach on %s stops at their first JIT compile, or on a WC refusal, this twin audits the rest of the candidate whole. Generated by scripts/ci/make_s5_profiles.py: '
            'regenerate, never hand-merge.' % (SHIP, AUDIT, ', '.join(WC_FLAGS), ', '.join(AUDIT_REMOVES), AUDIT_PARENT, AUDIT))


def specs():
    """[(profile name, parent name, what it is)] in the order they are written."""
    return [(AUDIT, AUDIT_PARENT, audit_description()), (AUDIT_NOWC, AUDIT_PARENT, nowc_description())]


def owned_names():
    """The audited twins and the candidate (a traffic profile make_fusion_profiles generates from fusion-wp/S5.json): the census tests that assert no other profile names an octo, tier or
    round-host flag exempt all three."""
    return NAMES + (SHIP,)


def twin_names():
    """The generated twin's name (the profile-enumerating tests exempt it through profile_twins; test_s5_profiles holds it)."""
    return NAMES


def parent_problems(profiles):
    """Why the twin cannot be generated, [] when it can."""
    problems = []
    for name in (SHIP4, SHIP, AUDIT_PARENT):
        if name not in profiles:
            problems.append('the parent profile %s is not defined (make_fusion_profiles.py --write, make_octo3_profiles.py --write and make_ship4_profiles.py --write first)' % name)
    if problems:
        return problems
    audit = profiles[AUDIT_PARENT]
    if audit.get('gate_only') is not True or (audit.get('env') or {}).get('QWEN_C2_GATE_PROFILE') != '1':
        problems.append('%s is not the gate-only audited twin of ship 4' % AUDIT_PARENT)
    for flag in AUDIT_ADDS:
        if flag in audit['env']:
            problems.append('%s already names %s: a parent never carries the knob it is twinned with' % (AUDIT_PARENT, flag))
    for flag in AUDIT_REMOVES:
        if flag not in audit['env']:
            problems.append('%s does not name %s: nothing to take out' % (AUDIT_PARENT, flag))
    waiver = profiles[SHIP].get(WAIVER_FIELD)
    if profiles[SHIP].get('gate_only') is True or not isinstance(waiver, dict):
        problems.append('%s is not a traffic profile with an owner traffic waiver' % SHIP)
    elif profiles[SHIP]['env'].get(WAIVER_ENV) != waiver.get('id'):
        problems.append('%s does not carry its waiver id in %s' % (SHIP, WAIVER_ENV))
    return problems


def generate(data):
    """data's profiles with the twin inserted right after the tp4/exact-end twins (every other entry unmoved); returns the new dict."""
    profiles = data['profiles']
    problems = parent_problems(profiles)
    if problems:
        raise ValueError('; '.join(problems))
    changes = candidate_changes(profiles)
    audit = copy.deepcopy(profiles[AUDIT_PARENT])
    audit['env'].update(changes)
    audit['env'].update(AUDIT_ADDS)
    for flag in AUDIT_REMOVES:
        audit['env'].pop(flag)
    audit['description'] = audit_description(changes)
    audit.pop(WAIVER_FIELD, None)
    audit.pop('gate_only', None)
    audit['gate_only'] = True
    nowc = copy.deepcopy(profiles[AUDIT_PARENT])
    nowc['env'].update(changes)
    nowc['env'].update(dict((flag, value) for flag, value in AUDIT_ADDS.items() if flag not in WC_FLAGS))
    nowc['description'] = nowc_description()
    nowc.pop(WAIVER_FIELD, None)
    nowc.pop('gate_only', None)
    nowc['gate_only'] = True
    generated = {AUDIT: audit, AUDIT_NOWC: nowc}
    remaining = [name for name in profiles if name not in generated]            # a previous generation is replaced below
    anchors = [name for name in remaining if name in xe.twin_names()]
    if not anchors:
        raise ValueError('the tp4/exact-end twins are not in the profiles file (make_xe_profiles.py --write first)')
    anchor = anchors[-1]
    result = {}
    for name in remaining:
        result[name] = profiles[name]
        if name == anchor:
            result.update(generated)
    out = dict(data)
    out['profiles'] = result
    return out


def render(data):
    return json.dumps(data, indent=2) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--path', default=str(PROFILES))
    arguments = parser.parse_args(argv)
    path = Path(arguments.path)
    current = path.read_text(encoding='utf-8')
    wanted = render(generate(json.loads(current)))
    if arguments.check:
        if wanted != current:
            sys.stderr.write('%s is not what make_s5_profiles.py generates from its parents: run it with --write\n' % path)
            return 1
        return 0
    if arguments.write:
        if wanted != current:
            with open(str(path), 'w', encoding='utf-8', newline='\n') as handle:
                handle.write(wanted)
        return 0
    parser.error('--write or --check')


if __name__ == '__main__':
    sys.exit(main())
