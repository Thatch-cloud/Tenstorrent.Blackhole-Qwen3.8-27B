"""The tp4/s7 gate-only audited twin of the ship-7 candidate, generated from the files it is made of (stdlib only).

    python3 scripts/ci/make_s7_profiles.py --write   regenerate the twin in scripts/ci/qwen_c2_profiles.json
    python3 scripts/ci/make_s7_profiles.py --check   exit 1 if the checked-in twin is not what its parents generate

NEVER hand-merge these entries into the profiles file. Run make_fusion_profiles.py --write FIRST (it writes the ship-7 candidate, `-fx-traffic-s7`, from scripts/ci/fusion-wp/S7.json, beside the earlier ship
candidates), then make_octo3_profiles.py, make_ship4_profiles.py, make_np1_profiles.py, make_xe_profiles.py, make_pf2_profiles.py, make_s5_profiles.py, make_s6_profiles.py (the audited twin of ship 6 is the
parent of these), make_sched2_profiles.py, make_pf3_profiles.py and make_pf3k_profiles.py, then this. The generators of the tp4/s7 chain place their twins after the last twin of the generators before them,
so each one's --check holds whichever ran last.

THE CANDIDATE is the traffic profile `-fx-traffic-s7` (docs/tp4-s7.md): the ship-6 profile (W3 WC + the adaptive Lever N governor on the ship-5 stack) plus the host tier's threaded upload
(QWEN_PREFIX_TIER_IO_THREADS, QWEN_PREFIX_TIER_VERIFY_THREADS), admission pipelining (QWEN_FAST_ADMISSION_SEED_FIRST), the memory-ledger trim (QWEN_FAST_ADMISSION_LEDGER_TRIM), prompt lookup beside engine
reuse (QWEN_FAST_LOOKUP_DRAFT), under ONE owner traffic waiver. Its gate-only twin, the audited attach arm:

  -fx-s7-audit      the ship-6 audited twin (`-fx-s6-audit`: every audit of the shipped stack, WC with its audit, the governor, the host tier with every instrument on) plus every difference of the candidate
                    from ship 6 EXCEPT the ledger trim (the audit's judge reads the ledger's points, which the trim removes).

THE TRACED MASKED TAILS (tp4/prefill-3, QWEN_FAST_PREFILL_TAIL_TRACE) ARE OUT of the candidate and of the twin: the first audited attaches of the lever (the tp4/s7 window, 2026-10-21) died at engine start on a
device read inside the trace capture (the oneq SDPA audit's readback, TT_FATAL "Reads are not supported during trace capture"; docs/tp4-s7.md). The code stays in the tree, default off, in no profile of this chain.

There is no gate-only timed twin: the candidate is a traffic profile and the control of every timed pair is the ship-6 profile itself. The twin is gate_only and unqualified.
"""

import argparse
import copy
import json
from pathlib import Path
import sys

import make_pf3_profiles as pf3
import make_pf3k_profiles as pf3k
import make_s5_profiles as s5
import make_s6_profiles as s6
import make_sched2_profiles as sched2

PROFILES = Path(__file__).resolve().parent / 'qwen_c2_profiles.json'

NAMESPACE = s5.NAMESPACE
SHIP6 = s6.SHIP                                     # the ship-6 profile: the control of every pair
SHIP = NAMESPACE + 'traffic-s7'                     # the candidate (generated by make_fusion_profiles.py from fusion-wp/S7.json)
AUDIT_PARENT = s6.AUDIT                             # the ship-6 audited twin
AUDIT = NAMESPACE + 's7-audit'
NAMES = (AUDIT,)
RETIRED = (NAMESPACE + 's7-audit-mid',)              # the second audited twin (traced buckets 256 and 512): gone with the traced tails; a previous generation's copy is dropped
WAIVER_ENV = s5.WAIVER_ENV
WAIVER_FIELD = s5.WAIVER_FIELD
LEDGER_TRIM = 'QWEN_FAST_ADMISSION_LEDGER_TRIM'
TAIL_KNOBS = (pf3.FLAG, pf3.AUDIT_FLAG, pf3.BUCKETS_FLAG, pf3.ARENA_FLAG)       # the traced tails' four knobs: in neither the candidate nor the twin
NOT_IN_THE_AUDITED_TWINS = (LEDGER_TRIM,)
MAX_NAME = 64


def candidate_changes(profiles):
    """{flag: value} the candidate sets that ship 6 does not (or sets differently), the waiver id aside: read from the two profiles."""
    old, new = profiles[SHIP6]['env'], profiles[SHIP]['env']
    return dict((flag, value) for flag, value in sorted(new.items()) if old.get(flag) != value and flag != WAIVER_ENV)


def audit_description(changes=None):
    shown = ', '.join('%s=%s' % pair for pair in sorted((changes or {}).items()))
    return ('GATE ONLY, UNQUALIFIED (tp4/s7, docs/tp4-s7.md; never traffic, never a timed arm). THE AUDITED ATTACH ARM of the ship-7 candidate %s. The parent is %s, the ship-6 audited '
            'twin (every audit of the shipped stack, WC with its audit, the adaptive governor, the host KV tier at its production size with every instrument on, the 13x10 grids), and this profile is that parent '
            'plus every difference of the candidate from ship 6 (%s) except the memory-ledger trim (%s: the audit\'s judge reads the ledger\'s points, which the trim removes), without an owner traffic waiver. The '
            'threaded upload, seed first and the lookup have no device instrument: their audit is the smoke check\'s (the lever lines) and the host tier\'s own digest checks. The traced masked tails are NOT in this '
            'profile (docs/tp4-s7.md). Generated by scripts/ci/make_s7_profiles.py: regenerate, never hand-merge.' % (SHIP, AUDIT_PARENT, shown or 'see the candidate', LEDGER_TRIM))


def specs():
    """[(profile name, parent name)] in the order they are written."""
    return [(AUDIT, AUDIT_PARENT)]


def owned_names():
    """The audited twin and the candidate (a traffic profile make_fusion_profiles generates from fusion-wp/S7.json): the census tests that assert no other profile names one of the levers exempt both."""
    return NAMES + (SHIP,)


def twin_names():
    """The generated twin's names (the profile-enumerating tests exempt them through profile_twins; test_s7_profiles holds them)."""
    return NAMES


def chain_names():
    """The names of the generators that run before this one: the twins this generator's own are placed after."""
    return tuple(s5.twin_names()) + tuple(s6.twin_names()) + tuple(sched2.twin_names()) + tuple(pf3.twin_names()) + tuple(pf3k.twin_names())


def parent_problems(profiles):
    """Why the twin cannot be generated, [] when it can."""
    problems = []
    for name in (SHIP6, SHIP, AUDIT_PARENT):
        if name not in profiles:
            problems.append('the parent profile %s is not defined (make_fusion_profiles.py --write, then make_s6_profiles.py --write first)' % name)
    problems += ['%s is %d characters, over the %d a profile name may have' % (name, len(name), MAX_NAME) for name in NAMES if len(name) > MAX_NAME]
    if problems:
        return problems
    audit = profiles[AUDIT_PARENT]
    if audit.get('gate_only') is not True or (audit.get('env') or {}).get('QWEN_C2_GATE_PROFILE') != '1':
        problems.append('%s is not the gate-only audited twin of ship 6' % AUDIT_PARENT)
    for name in (AUDIT_PARENT, SHIP):
        for flag in TAIL_KNOBS:
            if flag in profiles[name]['env']:
                problems.append('%s names %s: the traced masked tails are out of the s7 chain (their audited attaches died on a read inside the capture, docs/tp4-s7.md)' % (name, flag))
    waiver = profiles[SHIP].get(WAIVER_FIELD)
    if profiles[SHIP].get('gate_only') is True or not isinstance(waiver, dict):
        problems.append('%s is not a traffic profile with an owner traffic waiver' % SHIP)
    elif profiles[SHIP]['env'].get(WAIVER_ENV) != waiver.get('id'):
        problems.append('%s does not carry its waiver id in %s' % (SHIP, WAIVER_ENV))
    return problems


def generate(data):
    """data's profiles with the twins inserted right after the last twin of the generators before this one (every other entry unmoved); returns the new dict."""
    profiles = data['profiles']
    problems = parent_problems(profiles)
    if problems:
        raise ValueError('; '.join(problems))
    changes = candidate_changes(profiles)
    generated = {}
    for name, parent in specs():
        audit = copy.deepcopy(profiles[parent])
        audit['env'].update(dict((flag, value) for flag, value in changes.items() if flag not in NOT_IN_THE_AUDITED_TWINS))
        audit['description'] = audit_description(dict((flag, value) for flag, value in changes.items() if flag not in NOT_IN_THE_AUDITED_TWINS))
        audit.pop(WAIVER_FIELD, None)
        audit.pop('gate_only', None)
        audit['gate_only'] = True
        generated[name] = audit
    remaining = [name for name in profiles if name not in generated and name not in RETIRED]            # a previous generation is replaced below, a retired twin dropped
    anchors = [name for name in remaining if name in chain_names()]
    if not anchors:
        raise ValueError('the tp4/next-1 twins are not in the profiles file (make_s5_profiles.py --write first)')
    anchor = anchors[-1]
    result = {}
    for name in remaining:
        result[name] = profiles[name]
        if name == anchor:
            result.update(generated)
    out = dict(data)
    out['profiles'] = result
    return out


def render(data):
    return json.dumps(data, indent=2) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--path', default=str(PROFILES))
    arguments = parser.parse_args(argv)
    path = Path(arguments.path)
    current = path.read_text(encoding='utf-8')
    wanted = render(generate(json.loads(current)))
    if arguments.check:
        if wanted != current:
            sys.stderr.write('%s is not what make_s7_profiles.py generates from its parents: run it with --write\n' % path)
            return 1
        return 0
    if arguments.write:
        if wanted != current:
            with open(str(path), 'w', encoding='utf-8', newline='\n') as handle:
                handle.write(wanted)
        return 0
    parser.error('--write or --check')


if __name__ == '__main__':
    sys.exit(main())
