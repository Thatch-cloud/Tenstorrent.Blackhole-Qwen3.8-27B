"""The tp4/s6 gate-only audited twin of the ship-6 candidate, generated from the files it is made of (stdlib only).

    python3 scripts/ci/make_s6_profiles.py --write   regenerate the twin in scripts/ci/qwen_c2_profiles.json
    python3 scripts/ci/make_s6_profiles.py --check   exit 1 if the checked-in twin is not what its parents generate

NEVER hand-merge this entry into the profiles file. Run make_fusion_profiles.py --write FIRST (it writes the ship-6 candidate, `-fx-traffic-s6`, from scripts/ci/fusion-wp/S6.json, beside the ship-5 candidate),
then make_octo3_profiles.py, make_ship4_profiles.py, make_np1_profiles.py, make_xe_profiles.py, make_pf2_profiles.py and make_s5_profiles.py (the audited twin of ship 5 is this twin's parent), then this.

THE CANDIDATE is the traffic profile `-fx-traffic-s6` (docs/tp4-next2.md): the ship-5 profile that serves production, plus W3 WC (QWEN_FAST_TP4_GDN_WC) and the adaptive Lever N governor
(QWEN_FAST_LEVERN_ADAPTIVE), under ONE owner traffic waiver whose decision is PENDING. Its gate-only twin:

  -fx-s6-audit  THE AUDITED ATTACH ARM: the ship-5 audited twin (`-fx-s5-audit`: every audit of the shipped stack, the carry's audit, the hand-off's audit, W3 WC with its audit, the host tier with every
                instrument on) plus every difference of the candidate from ship 5 (read from the two profiles, so that it cannot drift): the governor's switch. W3 WC and its audit are already in the parent.
                The governor has no device instrument; its audit is the smoke check's (c2_smoke_check.levern_adaptive_problems reads the install line and the base=/target=/adaptive= fields of every step
                line), and the audited attach is where the governor, WC and every shipped audit run together for the first time.

There is no fallback twin without WC (WC rode the ship-5 audited twin in two card runs with 0 mismatches) and no gate-only TIMED twin: the candidate is a traffic profile whose waiver decision is PENDING,
and a profile whose decision does not start with APPROVED boots in a gate or a smoke and logs the word (only a build refuses to bake it), so the timed arm is the candidate itself and its control is the ship-5
profile (the profile that serves production). The twin is gate_only and unqualified.
"""

import argparse
import copy
import json
from pathlib import Path
import sys

import make_s5_profiles as s5

PROFILES = Path(__file__).resolve().parent / 'qwen_c2_profiles.json'

NAMESPACE = s5.NAMESPACE
SHIP5 = s5.SHIP                                     # the ship-5 profile that serves production: the control of every pair
SHIP = NAMESPACE + 'traffic-s6'                     # the candidate (generated by make_fusion_profiles.py from fusion-wp/S6.json)
AUDIT_PARENT = s5.AUDIT                             # the ship-5 audited twin
AUDIT = NAMESPACE + 's6-audit'
WAIVER_ENV = s5.WAIVER_ENV
WAIVER_FIELD = s5.WAIVER_FIELD
GOVERNOR_FLAG = 'QWEN_FAST_LEVERN_ADAPTIVE'
NAMES = (AUDIT,)


def candidate_changes(profiles):
    """{flag: value} the candidate sets that ship 5 does not (or sets differently), the waiver id aside: read from the two profiles."""
    old, new = profiles[SHIP5]['env'], profiles[SHIP]['env']
    return dict((flag, value) for flag, value in sorted(new.items()) if old.get(flag) != value and flag != WAIVER_ENV)


def audit_description(changes=None):
    shown = ', '.join('%s=%s' % pair for pair in sorted((changes or {}).items()))
    return ('GATE ONLY, UNQUALIFIED (tp4/s6, docs/tp4-next2.md; never traffic, never a timed arm). THE AUDITED ATTACH ARM of the ship-6 candidate %s. The parent is %s, the ship-5 audited twin (every '
            'audit of the shipped stack, the carry\'s audit, the hand-off\'s audit, W3 WC with its audit, the host KV tier at its production size with every instrument on, the 13x10 grids with all three '
            'sub-switches), and this profile is that parent plus exactly every difference of the candidate from ship 5 (%s), without an owner traffic waiver. So the adaptive Lever N governor (a prefill '
            'share of 0.9 and a 120 s deadline while one or two decoders are live, the decode-gap floor required) runs beside every audit of the shipped levers and beside W3 WC and its audit; the governor '
            'itself has no device instrument, its audit is the smoke check\'s (the install line, and the base=, target= and adaptive= fields of every step line). Generated by '
            'scripts/ci/make_s6_profiles.py: regenerate, never hand-merge.' % (SHIP, AUDIT_PARENT, shown or 'see the candidate'))


def specs():
    """[(profile name, parent name, what it is)] in the order they are written."""
    return [(AUDIT, AUDIT_PARENT, audit_description())]


def owned_names():
    """The audited twin and the candidate (a traffic profile make_fusion_profiles generates from fusion-wp/S6.json): the census tests that assert no other profile names an octo, tier or
    round-host flag exempt both."""
    return NAMES + (SHIP,)


def twin_names():
    """The generated twin's name (the profile-enumerating tests exempt it through profile_twins; test_s6_profiles holds it)."""
    return NAMES


def parent_problems(profiles):
    """Why the twin cannot be generated, [] when it can."""
    problems = []
    for name in (SHIP5, SHIP, AUDIT_PARENT):
        if name not in profiles:
            problems.append('the parent profile %s is not defined (make_fusion_profiles.py --write, then make_s5_profiles.py --write first)' % name)
    if problems:
        return problems
    audit = profiles[AUDIT_PARENT]
    if audit.get('gate_only') is not True or (audit.get('env') or {}).get('QWEN_C2_GATE_PROFILE') != '1':
        problems.append('%s is not the gate-only audited twin of ship 5' % AUDIT_PARENT)
    if GOVERNOR_FLAG in audit['env']:
        problems.append('%s already names %s: a parent never carries the knob it is twinned with' % (AUDIT_PARENT, GOVERNOR_FLAG))
    waiver = profiles[SHIP].get(WAIVER_FIELD)
    if profiles[SHIP].get('gate_only') is True or not isinstance(waiver, dict):
        problems.append('%s is not a traffic profile with an owner traffic waiver' % SHIP)
    elif profiles[SHIP]['env'].get(WAIVER_ENV) != waiver.get('id'):
        problems.append('%s does not carry its waiver id in %s' % (SHIP, WAIVER_ENV))
    if profiles[SHIP].get('env', {}).get(GOVERNOR_FLAG) != '1':
        problems.append('%s does not set %s=1: nothing for the twin to add' % (SHIP, GOVERNOR_FLAG))
    return problems


def generate(data):
    """data's profiles with the twin inserted right after the tp4/next-1 twins (every other entry unmoved); returns the new dict."""
    profiles = data['profiles']
    problems = parent_problems(profiles)
    if problems:
        raise ValueError('; '.join(problems))
    changes = candidate_changes(profiles)
    audit = copy.deepcopy(profiles[AUDIT_PARENT])
    audit['env'].update(changes)
    audit['description'] = audit_description(changes)
    audit.pop(WAIVER_FIELD, None)
    audit.pop('gate_only', None)
    audit['gate_only'] = True
    generated = {AUDIT: audit}
    remaining = [name for name in profiles if name not in generated]            # a previous generation is replaced below
    anchors = [name for name in remaining if name in s5.twin_names()]
    if not anchors:
        raise ValueError('the tp4/next-1 twins are not in the profiles file (make_s5_profiles.py --write first)')
    anchor = anchors[-1]
    result = {}
    for name in remaining:
        result[name] = profiles[name]
        if name == anchor:
            result.update(generated)
    out = dict(data)
    out['profiles'] = result
    return out


def render(data):
    return json.dumps(data, indent=2) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--path', default=str(PROFILES))
    arguments = parser.parse_args(argv)
    path = Path(arguments.path)
    current = path.read_text(encoding='utf-8')
    wanted = render(generate(json.loads(current)))
    if arguments.check:
        if wanted != current:
            sys.stderr.write('%s is not what make_s6_profiles.py generates from its parents: run it with --write\n' % path)
            return 1
        return 0
    if arguments.write:
        if wanted != current:
            with open(str(path), 'w', encoding='utf-8', newline='\n') as handle:
                handle.write(wanted)
        return 0
    parser.error('--write or --check')


if __name__ == '__main__':
    sys.exit(main())
