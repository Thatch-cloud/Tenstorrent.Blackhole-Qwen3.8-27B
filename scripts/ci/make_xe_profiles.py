"""The tp4/exact-end gate-only twins of the approved ship-4 profile: exact resume P0 on the production stack (docs/tp4-exact-end.md), generated from the files they are made of (stdlib only).

    python3 scripts/ci/make_xe_profiles.py --write   regenerate the twins in scripts/ci/qwen_c2_profiles.json
    python3 scripts/ci/make_xe_profiles.py --check   exit 1 if the checked-in twins are not what their parents generate

NEVER hand-merge these entries into the profiles file. Run make_fusion_profiles.py --write, make_octo3_profiles.py --write and make_ship4_profiles.py --write FIRST (the second twin copies the ship-4 audited
twin, the first the ship candidate), then this.

THE PROBLEM THEY SERVE. A returning sticky turn resumes at floor2048(P_prev) - 2048 and so re-prefills 2,048 + (P_prev mod 2048) tokens it already processed (about 3,070 on average, measured in production
as 2.95 million re-prefilled tokens over 996 turns). Exact resume P0 (QWEN_PREFIX_STICKY_UNDROP + QWEN_PREFIX_WINDOW_CARRY, docs/tp4-exact-resume.md 5.2) resumes at floor2048(P_prev), the cold prefill's own
last 2048 boundary, and carries the drafter window rows below it; it is byte-exact by construction (the cold prefill's own programs on the same bytes) and is a gate instrument today
(serving_c2_contract.exact_resume_problems: gate-only until a qualification record exists), so a traffic profile can never carry it.

  -fx-s4-xe        THE TIMED ARM: the ship candidate (-fx-traffic-s4) with the gate marker instead of its owner waiver id (as -fx-s4-nogrid13 does) plus exactly QWEN_PREFIX_STICKY_UNDROP=1 and
                   QWEN_PREFIX_WINDOW_CARRY=1. The returning-turn ABAB of references/fusion-jobs/XE times it against the candidate itself.
  -fx-s4-xe-audit  THE AUDITED ARM: the ship-4 audited twin (-fx-s4-audit: every audit of the candidate, the tile-aligned window's audit and the tier's instruments) plus those two and
                   QWEN_PREFIX_WINDOW_CARRY_AUDIT=1, so the carried rows are read back against the stored bytes and every sticky window's digest is logged for the cold-twin comparison.

Both are gate_only and unqualified. Nothing about the engine, the memory plan or any other flag differs from the parent.
"""

import argparse
import copy
import json
from pathlib import Path
import sys

import make_np1_profiles as np1
import make_octo_profiles
import make_ship4_profiles as ship4

PROFILES = Path(__file__).resolve().parent / 'qwen_c2_profiles.json'

NAMESPACE = ship4.NAMESPACE
SHIP = ship4.SHIP
AUDIT_PARENT = ship4.AUDIT
ARM = NAMESPACE + 's4-xe'
AUDIT = NAMESPACE + 's4-xe-audit'
LEVER_ENV = {'QWEN_PREFIX_STICKY_UNDROP': '1', 'QWEN_PREFIX_WINDOW_CARRY': '1'}
AUDIT_ENV = {'QWEN_PREFIX_WINDOW_CARRY_AUDIT': '1'}
WAIVER_ENV = ship4.WAIVER_ENV
WAIVER_FIELD = ship4.WAIVER_FIELD
MARKER_ENV = dict(make_octo_profiles.MARKER_ENV)
NAMES = (ARM, AUDIT)


def arm_description():
    return ('GATE ONLY, UNQUALIFIED (tp4/exact-end, docs/tp4-exact-end.md; never traffic). THE TIMED ARM of exact resume P0 on the production stack: the approved ship-4 profile %s with %s, so a returning sticky '
            'turn resumes at floor2048(P_prev) (the cold prefill\'s own last 2048 boundary) instead of floor2048(P_prev) - 2048, its drafter window\'s older rows carried from the turn that computed them (byte-exact: '
            'docs/tp4-exact-resume.md 5.2). The parent is %s and this profile is that parent plus exactly those two switches, the gate marker %s instead of its owner waiver id %s (the gate run admits the octo shape, as '
            '-fx-s4-nogrid13 does) and gate_only; its engine, memory plan and every other flag are the parent\'s byte for byte. The paired job set references/fusion-jobs/XE times it against the parent on '
            'returning turns. Generated by scripts/ci/make_xe_profiles.py: regenerate, never hand-merge.'
            % (SHIP, ', '.join('%s=%s' % pair for pair in sorted(LEVER_ENV.items())), SHIP, ', '.join('%s=%s' % pair for pair in sorted(MARKER_ENV.items())), WAIVER_ENV))


def audit_description():
    return ('GATE ONLY, UNQUALIFIED (tp4/exact-end, docs/tp4-exact-end.md; never traffic, never a timed arm). THE AUDITED ARM of exact resume P0 on the production stack: the ship-4 audited twin %s with %s and %s, '
            'so every audit of the candidate (the K/V page writer, the verify T2 audit, the pre-stage diff, the multi-user SDPA launch, the octo levers, the tile-aligned window and its audit, the host tier\'s instruments) runs '
            'beside the carry, the carried rows are read back against the stored bytes and every sticky prefill logs the sha256 of its whole drafter window for the prefix gate\'s cold-twin comparison. The parent is %s '
            'and this profile is that parent plus exactly those three switches and nothing else. Generated by scripts/ci/make_xe_profiles.py: regenerate, never hand-merge.'
            % (AUDIT_PARENT, ', '.join('%s=%s' % pair for pair in sorted(LEVER_ENV.items())), ', '.join('%s=%s' % pair for pair in sorted(AUDIT_ENV.items())), AUDIT_PARENT))


def specs():
    """[(profile name, parent name, what it is)] in the order they are written."""
    return [(ARM, SHIP, arm_description()), (AUDIT, AUDIT_PARENT, audit_description())]


def twin_names():
    """The generated twins' names (the profile-enumerating tests exempt them through profile_twins; test_xe_profiles holds each)."""
    return NAMES


def parent_problems(name, profile, audit):
    """Why `name` cannot be twinned, [] when it can."""
    problems = []
    env = profile.get('env') or {}
    for flag in tuple(LEVER_ENV) + tuple(AUDIT_ENV):
        if flag in env:
            problems.append('%s already names %s: a parent never carries the knob it is twinned with' % (name, flag))
    if audit:
        if profile.get('gate_only') is not True or env.get('QWEN_C2_GATE_PROFILE') != '1':
            problems.append('%s is not the gate-only audited twin of the ship candidate' % name)
    else:
        waiver = profile.get(WAIVER_FIELD)
        if profile.get('gate_only') is True or not isinstance(waiver, dict):
            problems.append('%s is not a traffic profile with an owner traffic waiver: the arm is that profile with the gate marker in its place' % name)
        elif env.get(WAIVER_ENV) != waiver.get('id'):
            problems.append('%s does not carry its waiver id in %s' % (name, WAIVER_ENV))
        for flag in MARKER_ENV:
            if flag in env:
                problems.append('%s already names %s: a traffic profile never carries the gate marker' % (name, flag))
    for flag in ('QWEN_PREFIX_REUSE', 'QWEN_FAST_STICKY_SESSIONS'):
        if env.get(flag) != '1':
            problems.append('%s does not name %s=1: exact resume needs prefix reuse with sticky sessions' % (name, flag))
    return problems


def generate(data):
    """data's profiles with the twins inserted right after the tp4/ship-4 twins (every other entry unmoved); returns the new dict."""
    profiles = data['profiles']
    for name in (AUDIT_PARENT, SHIP):
        if name not in profiles:
            raise ValueError('the parent profile %s is not defined (make_fusion_profiles.py --write, make_octo3_profiles.py --write and make_ship4_profiles.py --write, first)' % name)
    problems = parent_problems(AUDIT_PARENT, profiles[AUDIT_PARENT], True) + parent_problems(SHIP, profiles[SHIP], False)
    if problems:
        raise ValueError('; '.join(problems))
    arm = copy.deepcopy(profiles[SHIP])
    arm['env'].pop(WAIVER_ENV)
    arm['env'].update(MARKER_ENV)
    arm['env'].update(LEVER_ENV)
    arm['description'] = arm_description()
    arm.pop(WAIVER_FIELD, None)
    arm.pop('gate_only', None)
    arm['gate_only'] = True
    audit = copy.deepcopy(profiles[AUDIT_PARENT])
    audit['env'].update(LEVER_ENV)
    audit['env'].update(AUDIT_ENV)
    audit['description'] = audit_description()
    audit.pop('gate_only', None)
    audit['gate_only'] = True
    generated = {ARM: arm, AUDIT: audit}
    remaining = [name for name in profiles if name not in generated]            # a previous generation is replaced below
    anchors = [name for name in remaining if name in np1.twin_names()]            # (tp4/next-1: after the lone-user round's twins, which sit after the ship-4 twins; the ship-5 twins sit after these)
    if not anchors:
        raise ValueError('the tp4/ship-4 twins are not in the profiles file (make_ship4_profiles.py --write first)')
    anchor = anchors[-1]
    result = {}
    for name in remaining:
        result[name] = profiles[name]
        if name == anchor:
            result.update(generated)
    out = dict(data)
    out['profiles'] = result
    return out


def render(data):
    return json.dumps(data, indent=2) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--path', default=str(PROFILES))
    arguments = parser.parse_args(argv)
    path = Path(arguments.path)
    current = path.read_text(encoding='utf-8')
    wanted = render(generate(json.loads(current)))
    if arguments.check:
        if wanted != current:
            sys.stderr.write('%s is not what make_xe_profiles.py generates from its parents: run it with --write\n' % path)
            return 1
        return 0
    if arguments.write:
        if wanted != current:
            with open(str(path), 'w', encoding='utf-8', newline='\n') as handle:
                handle.write(wanted)
        return 0
    parser.error('--write or --check')


if __name__ == '__main__':
    sys.exit(main())
