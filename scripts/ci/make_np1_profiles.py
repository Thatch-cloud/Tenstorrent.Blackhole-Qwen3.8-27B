"""The tp4/np1-fastlane gate-only twins of the approved ship-4 profile: the lone-user padded round (QWEN_FAST_SOLO_PACKED=1, docs/tp4-np1-fastlane.md), generated from the files they are made of (stdlib only).

    python3 scripts/ci/make_np1_profiles.py --write   regenerate the twins in scripts/ci/qwen_c2_profiles.json
    python3 scripts/ci/make_np1_profiles.py --check   exit 1 if the checked-in twins are not what their parents generate

NEVER hand-merge these entries into the profiles file. Run make_fusion_profiles.py --write, make_octo3_profiles.py --write and make_ship4_profiles.py --write FIRST (the second twin copies the ship-4 audited
twin, the first the ship candidate), then this.

THE PROBLEM THEY SERVE. At one live seat the ship profile decodes on the 4-row per-request engine (83.9 ms a pass plus a 15.3 ms host gap, 3.7 tokens a round: about 37 tokens a second); at two it runs the
padded 64-row packed block (52.8 ms plus 19.6 ms, 13.6 tokens a round for the pair: about 94 a user). QWEN_FAST_SOLO_PACKED=1 lets a lone user (and a lone user of the other block) take that packed round, with
the third idle segment's K/V in a scratch page the model's KV allocation adds (idle_scratch.py). The approved traffic profile is NOT changed: the flag is a gate instrument (serving_c2_contract.OCTO_GATE_ONLY),
admitted in a gate run of a gate-only profile alone, so a traffic profile can never carry it.

  -fx-s4-np1        THE TIMED ARM: the ship candidate (-fx-traffic-s4) with the gate marker instead of its owner waiver id (as -fx-s4-nogrid13 does: the octo shape is then admitted by the gate run) plus
                    exactly QWEN_FAST_SOLO_PACKED=1. The ABAB of references/fusion-jobs/NP1 times it against the candidate itself.
  -fx-s4-np1-audit  THE AUDITED ATTACH ARM: the ship-4 audited twin (-fx-s4-audit: every audit of the candidate, the tier's instruments) plus exactly QWEN_FAST_SOLO_PACKED=1, so every audit runs on the padded
                    rounds of a lone user and of the pairs, with the third idle segment on the scratch page. (The extent audit, QWEN_FAST_EXTENT_AUDIT, is a gate step's own: a smoke job does not carry it.)

Both are gate_only and unqualified. Nothing about the engine, the memory plan or any other flag differs from the parent.
"""

import argparse
import copy
import json
from pathlib import Path
import sys

import make_octo_profiles
import make_ship4_profiles as ship4

PROFILES = Path(__file__).resolve().parent / 'qwen_c2_profiles.json'

NAMESPACE = ship4.NAMESPACE
SHIP = ship4.SHIP
AUDIT_PARENT = ship4.AUDIT
ARM = NAMESPACE + 's4-np1'
AUDIT = NAMESPACE + 's4-np1-audit'
FLAG = 'QWEN_FAST_SOLO_PACKED'
WAIVER_ENV = ship4.WAIVER_ENV
WAIVER_FIELD = ship4.WAIVER_FIELD
MARKER_ENV = dict(make_octo_profiles.MARKER_ENV)
NAMES = (ARM, AUDIT)


def arm_description():
    return ('GATE ONLY, UNQUALIFIED (tp4/np1-fastlane, docs/tp4-np1-fastlane.md; never traffic). THE TIMED ARM of the lone-user padded round: the approved ship-4 profile %s with %s=1, so a lone live user (and a lone '
            'user of either M3 block) takes the padded 64-row packed round instead of the 4-row per-request engine, its third idle segment parked on the KV scratch page the model\'s allocation adds (idle_scratch.py: '
            'one block more than vLLM\'s pool, 557,056 bytes a chip). The parent is %s and this profile is that parent plus exactly %s=1, the gate marker %s instead of its owner waiver id %s (the gate run admits the '
            'octo shape, as -fx-s4-nogrid13 does) and gate_only; its engine, memory plan and every other flag are the parent\'s byte for byte. The paired job set references/fusion-jobs/NP1 times it against the parent '
            'at one, two and four live seats. Generated by scripts/ci/make_np1_profiles.py: regenerate, never hand-merge.'
            % (SHIP, FLAG, SHIP, FLAG, ', '.join('%s=%s' % pair for pair in sorted(MARKER_ENV.items())), WAIVER_ENV))


def audit_description():
    return ('GATE ONLY, UNQUALIFIED (tp4/np1-fastlane, docs/tp4-np1-fastlane.md; never traffic, never a timed arm). THE AUDITED ATTACH ARM of the lone-user padded round: the ship-4 audited twin %s with %s=1, '
            'so every audit of the candidate (the K/V page writer\'s audit of every unit it writes, the verify T2 audit, the pre-stage diff and the two-block pre-stage audits, the multi-user SDPA launch\'s audit, the vglue, '
            'conv-gates and octo-lever audits, the host tier, the host read-backs sampled) runs on the padded rounds of a lone '
            'user and of a pair, whose third idle segment writes the KV scratch page (idle_scratch.py) while the other two write page 0. The parent is %s and this profile is that parent plus exactly %s=1 and '
            'nothing else. Generated by scripts/ci/make_np1_profiles.py: regenerate, never hand-merge.' % (AUDIT_PARENT, FLAG, AUDIT_PARENT, FLAG))


def specs():
    """[(profile name, parent name, what it is)] in the order they are written."""
    return [(ARM, SHIP, arm_description()), (AUDIT, AUDIT_PARENT, audit_description())]


def twin_names():
    """The generated twins' names (the profile-enumerating tests exempt them through profile_twins; test_np1_profiles holds each)."""
    return NAMES


def parent_problems(name, profile, audit):
    """Why `name` cannot be twinned, [] when it can."""
    problems = []
    env = profile.get('env') or {}
    if FLAG in env:
        problems.append('%s already names %s: a parent never carries the knob it is twinned with' % (name, FLAG))
    if audit:
        if profile.get('gate_only') is not True or env.get('QWEN_C2_GATE_PROFILE') != '1':
            problems.append('%s is not the gate-only audited twin of the ship candidate' % name)
    else:
        waiver = profile.get(WAIVER_FIELD)
        if profile.get('gate_only') is True or not isinstance(waiver, dict):
            problems.append('%s is not a traffic profile with an owner traffic waiver: the arm is that profile with the gate marker in its place' % name)
        elif env.get(WAIVER_ENV) != waiver.get('id'):
            problems.append('%s does not carry its waiver id in %s' % (name, WAIVER_ENV))
        for flag in MARKER_ENV:
            if flag in env:
                problems.append('%s already names %s: a traffic profile never carries the gate marker' % (name, flag))
    for key in ('QWEN_FAST_PADDED_BLOCK', 'QWEN_FAST_SINGLE_GATEUP'):
        # (the image's own ENV carries these two; a profile that names them must name what the flag needs)
        if key in env and env[key] != '1':
            problems.append('%s sets %s=%s: the lone-user round needs 1' % (name, key, env[key]))
    return problems


def generate(data):
    """data's profiles with the twins inserted right after the tp4/ship-4 twins (every other entry unmoved); returns the new dict."""
    profiles = data['profiles']
    for name in (AUDIT_PARENT, SHIP):
        if name not in profiles:
            raise ValueError('the parent profile %s is not defined (make_fusion_profiles.py --write, make_octo3_profiles.py --write and make_ship4_profiles.py --write, first)' % name)
    problems = parent_problems(AUDIT_PARENT, profiles[AUDIT_PARENT], True) + parent_problems(SHIP, profiles[SHIP], False)
    if problems:
        raise ValueError('; '.join(problems))
    arm = copy.deepcopy(profiles[SHIP])
    arm['env'].pop(WAIVER_ENV)
    arm['env'].update(MARKER_ENV)
    arm['env'][FLAG] = '1'
    arm['description'] = arm_description()
    arm.pop(WAIVER_FIELD, None)
    arm.pop('gate_only', None)
    arm['gate_only'] = True
    audit = copy.deepcopy(profiles[AUDIT_PARENT])
    audit['env'][FLAG] = '1'
    audit['description'] = audit_description()
    audit.pop('gate_only', None)
    audit['gate_only'] = True
    generated = {ARM: arm, AUDIT: audit}
    remaining = [name for name in profiles if name not in generated]            # a previous generation is replaced below
    anchors = [name for name in remaining if name in ship4.twin_names()]
    if not anchors:
        raise ValueError('the tp4/ship-4 twins are not in the profiles file (make_ship4_profiles.py --write first)')
    anchor = anchors[-1]
    result = {}
    for name in remaining:
        result[name] = profiles[name]
        if name == anchor:
            result.update(generated)
    out = dict(data)
    out['profiles'] = result
    return out


def render(data):
    return json.dumps(data, indent=2) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--path', default=str(PROFILES))
    arguments = parser.parse_args(argv)
    path = Path(arguments.path)
    current = path.read_text(encoding='utf-8')
    wanted = render(generate(json.loads(current)))
    if arguments.check:
        if wanted != current:
            sys.stderr.write('%s is not what make_np1_profiles.py generates from its parents: run it with --write\n' % path)
            return 1
        return 0
    if arguments.write:
        if wanted != current:
            with open(str(path), 'w', encoding='utf-8', newline='\n') as handle:
                handle.write(wanted)
        return 0
    parser.error('--write or --check')


if __name__ == '__main__':
    sys.exit(main())
