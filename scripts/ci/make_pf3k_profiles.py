"""The tp4/prefill-3 gate-only twins of the ship-5 candidate: the K-split of the chunked prefill SDPA for the tail passes (QWEN_FAST_SDPA_PF_KSPLIT, docs/tp4-prefill3-ksplit.md), generated from
the files they are made of (stdlib only).

    python3 scripts/ci/make_pf3k_profiles.py --write   regenerate the twins in scripts/ci/qwen_c2_profiles.json
    python3 scripts/ci/make_pf3k_profiles.py --check   exit 1 if the checked-in twins are not what their parents generate

NEVER hand-merge these entries into the profiles file. Run make_fusion_profiles.py --write, make_octo3_profiles.py --write, make_ship4_profiles.py --write and make_s5_profiles.py --write FIRST (the
control and the timed arm copy the ship-5 candidate `-fx-traffic-s5`, the audit twin the ship-5 audited twin `-fx-s5-audit`), then this.

THE PROBLEM THEY SERVE. A tail pass of 1,024 or 512 rows keeps 48 or 24 of the grid's 130 cores busy under the oneq call and a q chunk's K stream is serial on its core (13.51 us a block). The
K-split gives each q chunk up to four slices on idle cores and merges their partial results with the pinned ring merge. That is a NUMERICS change (the softmax is merged from partial results: the
output differs from the oneq call in the last bits; the waiver card is in the doc), so it is gate-only here: the approved traffic profile is NOT changed, the flag is not in it, and
serving_c2_contract.ksplit_problems refuses the flag on a traffic profile unless the owner's traffic waiver names it.

  -pf3k-s5-ctl     THE CONTROL OF THE TIMED PAIR: the ship-5 candidate with the gate marker instead of its owner waiver id and exactly QWEN_FAST_SDPA_PF_KSPLIT=0: the oneq call, byte for byte the approved
                   profile's, which the module (sdpa_pf_ksplit_tp) treats as off.
  -pf3k-s5         THE TIMED ARM: the same with QWEN_FAST_SDPA_PF_KSPLIT=1.
  -pf3k-s5-audit   THE AUDITED ATTACH ARM: the ship-5 audited twin (every audit of the candidate, the tier's instruments, W3 WC with its audit) plus QWEN_FAST_SDPA_PF_KSPLIT=1 and
                   QWEN_FAST_SDPA_PF_KSPLIT_AUDIT=1: the first 8 split calls and every 24th also run the oneq program and judge the two outputs by the waiver's statistic against its bound.

All three are gate_only and unqualified, and need the K64j-OQ-KS graft in the image (the K-split edits of the prefill factory). Nothing about the engine, the memory plan or any other flag differs from the
parent. The names are outside the fusion generator's namespace on purpose; the twins sit right after the last ship-5 twin, where the other packages' twins leave them alone.
"""

import argparse
import copy
import json
from pathlib import Path
import sys

import make_octo_profiles
import make_pf3_profiles as pf3
import make_s5_profiles as s5
import make_s6_profiles as s6
import make_sched2_profiles as sched2

PROFILES = Path(__file__).resolve().parent / 'qwen_c2_profiles.json'

PREFIX = 'c2-packed-tp4-8x262k-ship-prefix-levern-w2-er-pf3k-'
SHIP = s5.SHIP
AUDIT_PARENT = s5.AUDIT
CONTROL = PREFIX + 's5-ctl'
ARM = PREFIX + 's5'
AUDIT = PREFIX + 's5-audit'
FLAG = 'QWEN_FAST_SDPA_PF_KSPLIT'
AUDIT_FLAG = 'QWEN_FAST_SDPA_PF_KSPLIT_AUDIT'
ONEQ_FLAG = 'QWEN_FAST_SDPA_PF_ONEQ'
WAIVER_ENV = s5.WAIVER_ENV
WAIVER_FIELD = s5.WAIVER_FIELD
MARKER_ENV = dict(make_octo_profiles.MARKER_ENV)
NAMES = (CONTROL, ARM, AUDIT)
MAX_NAME = 64


def control_description():
    return ('GATE ONLY, UNQUALIFIED (tp4/prefill-3, docs/tp4-prefill3-ksplit.md; never traffic). THE CONTROL of the K-split pair: the ship-5 candidate %s with the gate marker %s instead of its owner '
            'waiver id %s and exactly %s=0 (the oneq call, unchanged: the module treats 0 as off). Its engine, memory plan and every other flag are the parent\'s byte for byte. Generated by '
            'scripts/ci/make_pf3k_profiles.py: regenerate, never hand-merge.' % (SHIP, ', '.join('%s=%s' % pair for pair in sorted(MARKER_ENV.items())), WAIVER_ENV, FLAG))


def arm_description():
    return ('GATE ONLY, UNQUALIFIED (tp4/prefill-3, docs/tp4-prefill3-ksplit.md; never traffic). THE TIMED ARM of the K-split of the tail passes: the ship-5 candidate %s with the gate marker instead of its '
            'owner waiver id and exactly %s=1: a 1,024-row or 512-row tail pass streams each q chunk\'s K blocks on two or four slices of idle cores and merges the partial results (a numerics change: '
            'the owner\'s waiver card is in the doc). 2,048-row chunk passes stay the oneq call. The parent is %s and this profile is the control %s with the flag turned on and nothing else. Needs '
            'the K64j-OQ-KS graft. Generated by scripts/ci/make_pf3k_profiles.py: regenerate, never hand-merge.' % (SHIP, FLAG, SHIP, CONTROL))


def audit_description():
    return ('GATE ONLY, UNQUALIFIED (tp4/prefill-3, docs/tp4-prefill3-ksplit.md; never traffic, never a timed arm). THE AUDITED ATTACH ARM of the K-split: the ship-5 audited twin %s (every audit of the candidate, '
            'the host tier\'s instruments, W3 WC with its audit) plus exactly %s=1 and %s=1: the first 8 split calls and then every 24th also run the oneq program and judge the two outputs by the '
            'waiver\'s statistic (the error in bf16 ulps of the row\'s scale) against its bound (\'[PINDIAG] sdpa prefill ksplit audit n=.. within_bound=True\'). Needs the K64j-OQ-KS graft. Generated by '
            'scripts/ci/make_pf3k_profiles.py: regenerate, never hand-merge.' % (AUDIT_PARENT, FLAG, AUDIT_FLAG))


def twin_names():
    """The generated twins' names (the profile-enumerating tests exempt them through profile_twins; test_pf3k_profiles holds each)."""
    return NAMES


def parent_problems(name, profile, audit):
    """Why `name` cannot be twinned, [] when it can."""
    problems = []
    env = profile.get('env') or {}
    for flag in (FLAG, AUDIT_FLAG):
        if flag in env:
            problems.append('%s already names %s: a parent never carries the knob it is twinned with' % (name, flag))
    if audit:
        if profile.get('gate_only') is not True or env.get('QWEN_C2_GATE_PROFILE') != '1':
            problems.append('%s is not the gate-only audited twin of the ship-5 candidate' % name)
    else:
        waiver = profile.get(WAIVER_FIELD)
        if profile.get('gate_only') is True or not isinstance(waiver, dict):
            problems.append('%s is not a traffic profile with an owner traffic waiver: the arm is that profile with the gate marker in its place' % name)
        elif env.get(WAIVER_ENV) != waiver.get('id'):
            problems.append('%s does not carry its waiver id in %s' % (name, WAIVER_ENV))
        for flag in MARKER_ENV:
            if flag in env:
                problems.append('%s already names %s: a traffic profile never carries the gate marker' % (name, flag))
    if env.get(ONEQ_FLAG) != '1':
        problems.append('%s does not run the oneq call (%s=1): the K-split extends it' % (name, ONEQ_FLAG))
    return problems


def traffic_twin(profile, value, description):
    twin = copy.deepcopy(profile)
    twin['env'].pop(WAIVER_ENV)
    twin['env'].update(MARKER_ENV)
    twin['env'][FLAG] = value
    twin['description'] = description
    twin.pop(WAIVER_FIELD, None)
    twin.pop('gate_only', None)
    twin['gate_only'] = True
    return twin


def generate(data):
    """data's profiles with the twins written after the last ship-5 twin (a previous generation is replaced; nothing else moves); returns the new dict."""
    profiles = data['profiles']
    for name in (AUDIT_PARENT, SHIP):
        if name not in profiles:
            raise ValueError('the parent profile %s is not defined (make_fusion_profiles.py --write, make_octo3_profiles.py --write, make_ship4_profiles.py --write and make_s5_profiles.py --write, first)' % name)
    problems = parent_problems(AUDIT_PARENT, profiles[AUDIT_PARENT], True) + parent_problems(SHIP, profiles[SHIP], False)
    problems += ['%s is %d characters, over the %d a profile name may have' % (name, len(name), MAX_NAME) for name in NAMES if len(name) > MAX_NAME]
    if problems:
        raise ValueError('; '.join(problems))
    audit = copy.deepcopy(profiles[AUDIT_PARENT])
    audit['env'][FLAG] = '1'
    audit['env'][AUDIT_FLAG] = '1'
    audit['description'] = audit_description()
    audit.pop('gate_only', None)
    audit['gate_only'] = True
    generated = {CONTROL: traffic_twin(profiles[SHIP], '0', control_description()), ARM: traffic_twin(profiles[SHIP], '1', arm_description()), AUDIT: audit}
    remaining = [name for name in profiles if name not in generated]            # a previous generation is replaced below
    anchors = [name for name in remaining if name in s5.twin_names() or name in s6.twin_names() or name in sched2.twin_names() or name in pf3.twin_names()]
    if not anchors:
        raise ValueError('the tp4/next-1 twins are not in the profiles file (make_s5_profiles.py --write first)')
    anchor = anchors[-1]            # the last ship-5 twin or traced-tail twin (make_pf3_profiles anchors on the ship-5 twins, so this group follows that one and the generators commute)
    result = {}
    for name in remaining:
        result[name] = profiles[name]
        if name == anchor:
            result.update(generated)
    out = dict(data)
    out['profiles'] = result
    return out


def render(data):
    return json.dumps(data, indent=2) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--path', default=str(PROFILES))
    arguments = parser.parse_args(argv)
    path = Path(arguments.path)
    current = path.read_text(encoding='utf-8')
    wanted = render(generate(json.loads(current)))
    if arguments.check:
        if wanted != current:
            sys.stderr.write('%s is not what make_pf3k_profiles.py generates from its parents: run it with --write\n' % path)
            return 1
        return 0
    if arguments.write:
        if wanted != current:
            with open(str(path), 'w', encoding='utf-8', newline='\n') as handle:
                handle.write(wanted)
        return 0
    parser.error('--write or --check')


if __name__ == '__main__':
    sys.exit(main())
