"""The op-fusion programme's integration scaffolding (docs/tp4-fusion.md), generated from the work packages' manifests (stdlib only).

    python3 scripts/ci/make_fusion_profiles.py --write    regenerate every generated block from scripts/ci/fusion-wp/*.json
    python3 scripts/ci/make_fusion_profiles.py --check    exit 1 if a checked-in block is not what the manifests generate
    python3 scripts/ci/make_fusion_profiles.py --report   one line per manifest entry and where it landed (or why it already was there)

Each work package (WP1 S1 argmax, WP2 K/V writer, WP5 CCL options, WP6 drafter reduce and MLP branch, WP7 drafter attention and permutes) owns its own
modules and writes ONE manifest, scripts/ci/fusion-wp/<WP>.json (the schema is in scripts/ci/fusion-wp/SCHEMA.md). It never edits the five shared files below;
this generator does, inside blocks fenced by `fusion-wp begin` / `fusion-wp end` comment lines, which nothing else edits (NEVER hand-merge a fenced block: after
a merge, regenerate):

  scripts/ci/qwen_c2_profiles.json         per lever, two GATE-ONLY twins of the production profile (PARENT below, byte for byte but for the owner traffic waiver
                                           and gate_only): -fx-<id> (the flag on: the timed arm) and -fx-<id>-audit (plus the lever's _AUDIT flag: the exactness arm)
  scripts/ci/c2_smoke_check.py             FUSION_LEVERS / FUSION_AUDITS, the marker tables fusion_problems() reads (a fall-back line fails the smoke; a profile that
                                           asks for the lever and logs no engaged line fails; an audit flag with no 'exact=True' audit line fails), and FUSION_RULES,
                                           the packages' own stricter rules (host-side modules with problems(env, container_text)) that it calls once per arm
  docker/qwen-c2-overlay.txt               the image copy list: the ONE list (c2_overlay.py); the P8 copy lists are not touched
  .github/workflows/qwen-integration-cpu.yml   the CPU allowlist: the regression step the any-ref CPU suite runs
  scripts/ci/tp_addresses.py               twin rows, when a package binds a twin module or class through tp_addresses

The generator is deterministic (manifests in file-name order, entries in file order, no clock, no host state), idempotent, and refuses what it cannot place:
an unknown key, a file the manifest names that the tree lacks, a flag already in the parent, two packages naming one flag or one id, an overlay line c2_overlay's
parser refuses. With no manifest every block is empty and the five files are what they were before the programme.
"""

