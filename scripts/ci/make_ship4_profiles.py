"""The tp4/ship-4 gate-only twins of the combined ship candidate, generated from the files it is made of (stdlib only).

    python3 scripts/ci/make_ship4_profiles.py --write   regenerate the twins in scripts/ci/qwen_c2_profiles.json
    python3 scripts/ci/make_ship4_profiles.py --check   exit 1 if the checked-in twins are not what their parents generate

NEVER hand-merge these entries into the profiles file. Run make_fusion_profiles.py --write FIRST (it writes the ship candidate, whose env the second twin copies) and make_octo3_profiles.py
(it writes the octo-3 twins, whose audited twin is the first twin's parent), then this.

THE SHIP CANDIDATE is the traffic profile `-fx-traffic-s4` (scripts/ci/fusion-wp/S4.json, generated by make_fusion_profiles.py): the approved fusion ship profile (`-fx-traffic`) plus the prefill SDPA
with one q chunk per core, the 13x10 matmul grids, octo-T8 with its three levers, the tile-aligned drafter window, the host KV tier with the preconverted checkpoints and the third block's memory plan, under
ONE owner traffic waiver (decision PENDING). Nothing in it has run on a card together. Its two gate-only twins:

  -fx-s4-audit      THE AUDITED ATTACH ARM: the octo-3 audited twin of the combined prefill arm (`-fx-all-oneq-grid13-octo3-audit`: every fusion lever with its audit, the oneq and grid13 audits, the
                    octo levers with the bundle, glue and F1 audits, the tile-aligned window and its audit, the host read-back audits SAMPLED) plus the host KV tier with every tier instrument on (the
                    restored blocks read back and compared, every digest checked, the preconverted tensors compared with today's conversion) and the multi-user SDPA launch's own audit, exactly the
                    env prefix_tier_profiles gives its audit twin. Not a timing arm; the arm of the audited attach A1, the concurrent tier gate TC1 and the quota gate TQ1.
  -fx-s4-nogrid13   THE SWITCHABLE CONTROL: the ship candidate without QWEN_FAST_GRID13 (the one line of the candidate whose own decode ABAB, the M1 programme's F2 window, may still say loss; the
                    candidate carries only its prefill and drafter sub-switches, the audited twin all three), as a
                    gate-only profile (the gate marker instead of the waiver id, no owner waiver). The paired job N1 times it against the candidate.

Both are gate_only and unqualified.
"""

import argparse
import copy
import json
from pathlib import Path
import sys

import make_octo3_profiles
import make_octo_profiles
import make_prefix_tier_profiles as tier

PROFILES = Path(__file__).resolve().parent / 'qwen_c2_profiles.json'

NAMESPACE = 'c2-packed-tp4-8x262k-ship-prefix-levern-w2-er-fx-'
SHIP_NAME = 'traffic-s4'
SHIP = NAMESPACE + SHIP_NAME
AUDIT_PARENT = make_octo3_profiles.FX_ALL_PREFILL + '-octo3-audit'
AUDIT = NAMESPACE + 's4-audit'
NOGRID13 = NAMESPACE + 's4-nogrid13'
GRID13 = 'QWEN_FAST_GRID13'
WAIVER_ENV = 'QWEN_FAST_OCTO_WAIVER'
WAIVER_FIELD = 'owner_traffic_waiver'
MARKER_ENV = dict(make_octo_profiles.MARKER_ENV)
TIER_AUDIT_ENV = dict(tier.ENV)
NAMES = (AUDIT, NOGRID13)


def audit_description():
    return ('GATE ONLY, UNQUALIFIED (tp4/ship-4, docs/tp4-ship4.md; never traffic, never a timed arm). The audited twin of the combined ship candidate %s. The parent is %s, the octo-3 audited '
            'twin of the combined prefill arm (every fusion lever of the candidate with its _AUDIT flag, the prefill SDPA with one q chunk per core and the 13x10 matmul grids with their audits (QWEN_FAST_GRID13=1: all three sub-switches, including the decode verify sub-switch that the candidate holds out until an audited attach has compared it), octo-T8 '
            'with its three levers and their audits, the tile-aligned drafter window with its audit, the host read-back audits SAMPLED by audit_sampling, the third block\'s memory plan), and this profile is '
            'that parent plus exactly %s and nothing else, without an owner traffic waiver: the host KV tier at its production size with EVERY instrument on (each restored block read back and compared '
            'with the bytes written, each block\'s digest checked at restore, the preconverted checkpoints compared with today\'s conversion on card) and the multi-user SDPA launch\'s own audit, which the '
            'gate\'s extent audit needs beside W2. The tier\'s kill-switch file is %s inside the container. Needs the qwen_kv_read extension, version 2. Generated by scripts/ci/make_ship4_profiles.py: '
            'regenerate, never hand-merge.' % (SHIP, AUDIT_PARENT, ', '.join('%s=%s' % pair for pair in sorted(TIER_AUDIT_ENV.items())), tier.OFF_PATH))


def nogrid13_description():
    return ('GATE ONLY, UNQUALIFIED (tp4/ship-4, docs/tp4-ship4.md; never traffic). The SWITCHABLE CONTROL of the combined ship candidate %s: that profile without %s (the M1 programme\'s 13x10 '
            'matmul grids, here their prefill and drafter sub-switches, whose own decode ABAB may still say loss) and as a gate-only profile (%s instead of %s, no owner traffic waiver). Everything else is the candidate byte for byte: its env, '
            'its engine and the third block\'s memory plan. The paired job N1 of references/fusion-jobs/ship4 times it against the candidate; a loss there is answered by deleting the %s line from the '
            'ship entry of scripts/ci/fusion-wp/S4.json and regenerating. Generated by scripts/ci/make_ship4_profiles.py: regenerate, never hand-merge.'
            % (SHIP, GRID13, ', '.join('%s=%s' % pair for pair in sorted(MARKER_ENV.items())), WAIVER_ENV, GRID13))


def specs():
    """[(profile name, parent name, what it is)] in the order they are written."""
    return [(AUDIT, AUDIT_PARENT, audit_description()), (NOGRID13, SHIP, nogrid13_description())]


def twin_names():
    """The generated twins' names (the profile-enumerating tests exempt them through profile_twins; test_ship4_profiles holds each)."""
    return NAMES


def ship_names():
    """The combined ship candidate (a traffic profile make_fusion_profiles generates from fusion-wp/S4.json): not a twin, not gate-only. The census tests that assert no other profile names an
    octo, prefill or tier flag exempt it with the twins."""
    return (SHIP,)


def owned_names():
    return NAMES + ship_names()


def parent_problems(name, profile, audit):
    """Why `name` cannot be twinned, [] when it can."""
    problems = []
    env = profile.get('env') or {}
    if audit:
        for flag in TIER_AUDIT_ENV:
            if flag in env:
                problems.append('%s already names %s: a parent never carries the knob it is twinned with' % (name, flag))
        if profile.get('gate_only') is not True:
            problems.append('%s is not gate_only: the audit twin\'s parent is the octo-3 audited twin' % name)
        if env.get('QWEN_FAST_SDPA_PF_ONEQ_AUDIT') != '1' or env.get('QWEN_FAST_GRID13_AUDIT') != '1' or env.get(make_octo3_profiles.OCTO) != 'live':
            problems.append('%s is not the audited combined prefill arm with the octo levers' % name)
    else:
        waiver = profile.get(WAIVER_FIELD)
        if profile.get('gate_only') is True or not isinstance(waiver, dict):
            problems.append('%s is not a traffic profile with an owner traffic waiver: the control is that profile without one line' % name)
        elif env.get(WAIVER_ENV) != waiver.get('id'):
            problems.append('%s does not carry its waiver id in %s' % (name, WAIVER_ENV))
        if not env.get(GRID13):
            problems.append('%s does not set %s: the control would be the candidate itself' % (name, GRID13))
        for flag in MARKER_ENV:
            if flag in env:
                problems.append('%s already names %s: a traffic profile never carries the gate marker' % (name, flag))
    return problems


def generate(data):
    """data's profiles with the twins inserted right after the tp4/octo-3 twins (every other entry unmoved); returns the new dict."""
    profiles = data['profiles']
    for name in (AUDIT_PARENT, SHIP):
        if name not in profiles:
            raise ValueError('the parent profile %s is not defined (make_fusion_profiles.py --write, then make_octo3_profiles.py --write, first)' % name)
    problems = parent_problems(AUDIT_PARENT, profiles[AUDIT_PARENT], True) + parent_problems(SHIP, profiles[SHIP], False)
    if problems:
        raise ValueError('; '.join(problems))
    audit = copy.deepcopy(profiles[AUDIT_PARENT])
    audit['env'].update(TIER_AUDIT_ENV)
    audit['description'] = audit_description()
    audit.pop(WAIVER_FIELD, None)
    audit.pop('gate_only', None)
    audit['gate_only'] = True
    control = copy.deepcopy(profiles[SHIP])
    control['env'].pop(GRID13)
    control['env'].pop(WAIVER_ENV)
    control['env'].update(MARKER_ENV)
    control['description'] = nogrid13_description()
    control.pop(WAIVER_FIELD, None)
    control.pop('gate_only', None)
    control['gate_only'] = True
    generated = {AUDIT: audit, NOGRID13: control}
    remaining = [name for name in profiles if name not in generated]            # a previous generation is replaced below
    anchors = [name for name in remaining if name in make_octo3_profiles.twin_names()]
    if not anchors:
        raise ValueError('the tp4/octo-3 twins are not in the profiles file (make_octo3_profiles.py --write first)')
    anchor = anchors[-1]
    result = {}
    for name in remaining:
        result[name] = profiles[name]
        if name == anchor:
            result.update(generated)
    out = dict(data)
    out['profiles'] = result
    return out


def render(data):
    return json.dumps(data, indent=2) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--path', default=str(PROFILES))
    arguments = parser.parse_args(argv)
    path = Path(arguments.path)
    current = path.read_text(encoding='utf-8')
    wanted = render(generate(json.loads(current)))
    if arguments.check:
        if wanted != current:
            sys.stderr.write('%s is not what make_ship4_profiles.py generates from its parents: run it with --write\n' % path)
            return 1
        return 0
    if arguments.write:
        if wanted != current:
            with open(str(path), 'w', encoding='utf-8', newline='\n') as handle:
                handle.write(wanted)
        return 0
    parser.error('--write or --check')


if __name__ == '__main__':
    sys.exit(main())
