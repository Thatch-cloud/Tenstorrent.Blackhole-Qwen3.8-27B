"""The tp4/prefill-3 gate-only twins of the ship-5 candidate: the masked tail pass of a prompt as a trace replay (QWEN_FAST_PREFILL_TAIL_TRACE, docs/tp4-prefill3.md), generated from the
files they are made of (stdlib only).

    python3 scripts/ci/make_pf3_profiles.py --write   regenerate the twins in scripts/ci/qwen_c2_profiles.json
    python3 scripts/ci/make_pf3_profiles.py --check   exit 1 if the checked-in twins are not what their parents generate

NEVER hand-merge these entries into the profiles file. Run make_fusion_profiles.py --write, make_octo3_profiles.py --write, make_ship4_profiles.py --write, make_pf2_profiles.py --write and
make_s5_profiles.py --write FIRST (the timed twins copy the ship-5 candidate, the audit twin the ship-5 audited twin WITHOUT W3 WC), then this.

THE PROBLEM THEY SERVE. The masked tail pass of every prompt below the 2,048-row bucket is host-bound: ~3,155 eagerly dispatched ops, a flat 320 to 410 ms before any attention (docs/tp4-prefill-2.md
section 3.2). QWEN_FAST_PREFILL_TAIL_TRACE=1 replays a captured trace instead (prefill_tail_trace.py). The approved traffic profile is NOT changed: the flag is not in it, and a traffic profile that
wants it needs an owner traffic waiver that names it.

  -pf3-s5-ctl     THE CONTROL OF THE TIMED PAIR: the ship-5 candidate (-fx-traffic-s5) with the gate marker instead of its owner waiver id and exactly QWEN_FAST_PREFILL_TAIL_TRACE=0: the eager tail, byte for
                  byte the candidate's, which also prints the '[PF3] tail mode=eager' timing line so that both arms of the pair print the quantity the lever changes.
  -pf3-s5         THE TIMED ARM: the same with QWEN_FAST_PREFILL_TAIL_TRACE=1 and the arena at ARENA_MB (the default of the module, an ESTIMATE).
  -pf3-s5-a160    THE ARENA LADDER, one rung down (160 MB): the attach itself is the measurement (the warm records everything the captures free and fails by name when any of it lies outside the arena).
  -pf3-s5-a80     the next rung (80 MB).
  -pf3-s5-audit   THE AUDITED ATTACH ARM: the ship-5 audited twin without W3 WC (-fx-s5-audit-nowc: every audit of the candidate) plus QWEN_FAST_PREFILL_TAIL_TRACE=1,
                  QWEN_FAST_PREFILL_TAIL_TRACE_AUDIT=1 and the buckets 128 and 1024: the first 8 traced tails and every 24th run the stock pass beside the replay and require every GDN state, every
                  real output row and every tap row byte equal ('[PINDIAG] prefill tail trace audit n=.. exact=True'). Two buckets and not four because the audited stack leaves the trace region
                  114.8 MB free after the packed round (the traffic candidate 251.9 MB): four traces would not fit it at the high end of the estimate.
  -pf3-s5-audit-mid  the same for the buckets 256 and 512 (the other two programs: the stock SDPA at two q chunks a head, and the one-q-per-core call at 512 rows).

All are gate_only and unqualified. Nothing about the engine, the memory plan or any other flag differs from the parent. The names are outside the fusion generator's namespace on purpose; the twins sit
right after the ship-5 audited twins.
"""

import argparse
import copy
import json
from pathlib import Path
import sys

import make_octo_profiles
import make_s5_profiles as s5
import make_s6_profiles as s6
import make_sched2_profiles as sched2
import make_ship4_profiles as ship4

PROFILES = Path(__file__).resolve().parent / 'qwen_c2_profiles.json'

PREFIX = 'c2-packed-tp4-8x262k-ship-prefix-levern-w2-er-pf3-'
SHIP = s5.SHIP
AUDIT_PARENT = s5.AUDIT_NOWC
CONTROL = PREFIX + 's5-ctl'
ARM = PREFIX + 's5'
LADDER = (('a160', '160'), ('a80', '80'))
AUDIT = PREFIX + 's5-audit'
AUDIT_MID = PREFIX + 's5-audit-mid'
BUCKETS_FLAG = 'QWEN_FAST_PREFILL_TAIL_TRACE_BUCKETS'
AUDIT_BUCKETS = (('128,1024', AUDIT), ('256,512', AUDIT_MID))
FLAG = 'QWEN_FAST_PREFILL_TAIL_TRACE'
AUDIT_FLAG = 'QWEN_FAST_PREFILL_TAIL_TRACE_AUDIT'
ARENA_FLAG = 'QWEN_FAST_PREFILL_TAIL_TRACE_ARENA_MB'
ARENA_MB = '320'                    # prefill_tail_trace.DEFAULT_ARENA_MB, pinned equal by test_pf3_profiles (an ESTIMATE until the card ladder)
WAIVER_ENV = ship4.WAIVER_ENV
WAIVER_FIELD = ship4.WAIVER_FIELD
MARKER_ENV = dict(make_octo_profiles.MARKER_ENV)
NAMES = (CONTROL, ARM) + tuple(PREFIX + 's5-' + rung for rung, _mb in LADDER) + (AUDIT, AUDIT_MID)
MAX_NAME = 64


def control_description():
    return ('GATE ONLY, UNQUALIFIED (tp4/prefill-3, docs/tp4-prefill3.md; never traffic). THE CONTROL of the traced-tail pair: the ship-5 candidate %s with the gate marker %s instead of its owner waiver id '
            '%s and exactly %s=0 (the eager masked tail, unchanged; the route also prints its \'[PF3] tail mode=eager\' timing line, so both arms of the pair print the quantity the lever changes). '
            'Its engine, memory plan and every other flag are the parent\'s byte for byte. Generated by scripts/ci/make_pf3_profiles.py: regenerate, never hand-merge.'
            % (SHIP, ', '.join('%s=%s' % pair for pair in sorted(MARKER_ENV.items())), WAIVER_ENV, FLAG))


def arm_description(megabytes=ARENA_MB):
    return ('GATE ONLY, UNQUALIFIED (tp4/prefill-3, docs/tp4-prefill3.md; never traffic). THE %s of the traced tails: the ship-5 candidate %s with the gate marker instead of its owner waiver id and exactly '
            '%s=1 and %s=%s: the masked tail pass of a prompt below the 2,048-row bucket is a trace replay (prefill_tail_trace.py) over persistent buffers, its pad rows inert through the gates, its pad '
            'K/V blocks in NP1\'s scratch page, its captures inside an arena of %s MB a chip. The parent is %s and this profile is the control %s with the flag turned on and the arena named, and nothing '
            'else. Generated by scripts/ci/make_pf3_profiles.py: regenerate, never hand-merge.'
            % ('TIMED ARM' if megabytes == ARENA_MB else 'ARENA LADDER RUNG (%s MB)' % megabytes, SHIP, FLAG, ARENA_FLAG, megabytes, megabytes, SHIP, CONTROL))


def audit_description(buckets):
    return ('GATE ONLY, UNQUALIFIED (tp4/prefill-3, docs/tp4-prefill3.md; never traffic, never a timed arm). THE AUDITED ATTACH ARM of the traced tails (buckets %s): the ship-5 audited twin without W3 WC %s '
            '(every audit of the candidate, the host tier\'s instruments, the 13x10 grids) plus exactly %s=1, %s=%s, %s=%s and %s=1: the first 8 traced tails and then every 24th run the stock pass '
            'beside the replay and require every GDN recurrent state, conv carry and conv window, every real output row and every drafter tap row byte equal (\'[PINDIAG] prefill tail trace audit '
            'n=.. exact=True\'); the stock result is what the request is served. Two buckets a twin because the audited stack leaves the trace region 114.8 MB free. Generated by '
            'scripts/ci/make_pf3_profiles.py: regenerate, never hand-merge.' % (buckets, AUDIT_PARENT, FLAG, ARENA_FLAG, ARENA_MB, BUCKETS_FLAG, buckets, AUDIT_FLAG))


def twin_names():
    """The generated twins' names (the profile-enumerating tests exempt them through profile_twins; test_pf3_profiles holds each)."""
    return NAMES


def parent_problems(name, profile, audit):
    """Why `name` cannot be twinned, [] when it can."""
    problems = []
    env = profile.get('env') or {}
    for flag in (FLAG, AUDIT_FLAG, ARENA_FLAG, BUCKETS_FLAG):
        if flag in env:
            problems.append('%s already names %s: a parent never carries the knob it is twinned with' % (name, flag))
    if audit:
        if profile.get('gate_only') is not True or env.get('QWEN_C2_GATE_PROFILE') != '1':
            problems.append('%s is not the gate-only audited twin of the ship candidate' % name)
    else:
        waiver = profile.get(WAIVER_FIELD)
        if profile.get('gate_only') is True or not isinstance(waiver, dict):
            problems.append('%s is not a traffic profile with an owner traffic waiver: the arm is that profile with the gate marker in its place' % name)
        elif env.get(WAIVER_ENV) != waiver.get('id'):
            problems.append('%s does not carry its waiver id in %s' % (name, WAIVER_ENV))
        for flag in MARKER_ENV:
            if flag in env:
                problems.append('%s already names %s: a traffic profile never carries the gate marker' % (name, flag))
    if env.get('QWEN_FAST_LEVER_N') != '1':
        problems.append('%s does not run Lever N (QWEN_FAST_LEVER_N=1): the traced tail is a lever of its route' % name)
    if env.get('QWEN_FAST_SOLO_PACKED') != '1':
        problems.append('%s does not run the lone-user padded round (QWEN_FAST_SOLO_PACKED=1): the traced tail writes its pad blocks to that round\'s KV scratch page' % name)
    if env.get('QWEN_FAST_GDN_PREFILL_CONV_AUDIT') is None:
        problems.append('%s does not name the prefill conv audit knob: the profile family the traced tail was derived on' % name)
    return problems


def traffic_twin(profile, flags, description):
    twin = copy.deepcopy(profile)
    twin['env'].pop(WAIVER_ENV)
    twin['env'].update(MARKER_ENV)
    twin['env'].update(flags)
    twin['description'] = description
    twin.pop(WAIVER_FIELD, None)
    twin.pop('gate_only', None)
    twin['gate_only'] = True
    return twin


def generate(data):
    """data's profiles with the twins written after the ship-5 audited twins (a previous generation is replaced; nothing else moves); returns the new dict."""
    profiles = data['profiles']
    for name in (AUDIT_PARENT, SHIP):
        if name not in profiles:
            raise ValueError('the parent profile %s is not defined (make_fusion_profiles.py --write, make_octo3_profiles.py --write, make_ship4_profiles.py --write, make_pf2_profiles.py --write and '
                             'make_s5_profiles.py --write, first)' % name)
    problems = parent_problems(AUDIT_PARENT, profiles[AUDIT_PARENT], True) + parent_problems(SHIP, profiles[SHIP], False)
    problems += ['%s is %d characters, over the %d a profile name may have' % (name, len(name), MAX_NAME) for name in NAMES if len(name) > MAX_NAME]
    if problems:
        raise ValueError('; '.join(problems))
    generated = {CONTROL: traffic_twin(profiles[SHIP], {FLAG: '0'}, control_description()),
                 ARM: traffic_twin(profiles[SHIP], {FLAG: '1', ARENA_FLAG: ARENA_MB}, arm_description())}
    for rung, megabytes in LADDER:
        generated[PREFIX + 's5-' + rung] = traffic_twin(profiles[SHIP], {FLAG: '1', ARENA_FLAG: megabytes}, arm_description(megabytes))
    for buckets, name in AUDIT_BUCKETS:
        audit = copy.deepcopy(profiles[AUDIT_PARENT])
        audit['env'].update({FLAG: '1', ARENA_FLAG: ARENA_MB, BUCKETS_FLAG: buckets, AUDIT_FLAG: '1'})
        audit['description'] = audit_description(buckets)
        audit.pop('gate_only', None)
        audit['gate_only'] = True
        generated[name] = audit
    remaining = [name for name in profiles if name not in generated]            # a previous generation is replaced below
    anchors = [name for name in remaining if name in s5.twin_names() or name in s6.twin_names() or name in sched2.twin_names()]            # (the tp4/s7 chain: ship-5 twins, the ship-6 audited twin, the sched-2 twins, then these; the generators commute)
    if not anchors:
        raise ValueError('the ship-5 audited twins are not in the profiles file (make_s5_profiles.py --write first)')
    anchor = anchors[-1]
    result = {}
    for name in remaining:
        result[name] = profiles[name]
        if name == anchor:
            result.update(generated)
    out = dict(data)
    out['profiles'] = result
    return out


def render(data):
    return json.dumps(data, indent=2) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--path', default=str(PROFILES))
    arguments = parser.parse_args(argv)
    path = Path(arguments.path)
    current = path.read_text(encoding='utf-8')
    wanted = render(generate(json.loads(current)))
    if arguments.check:
        if wanted != current:
            sys.stderr.write('%s is not what make_pf3_profiles.py generates from its parents: run it with --write\n' % path)
            return 1
        return 0
    if arguments.write:
        if wanted != current:
            with open(str(path), 'w', encoding='utf-8', newline='\n') as handle:
                handle.write(wanted)
        return 0
    parser.error('--write or --check')


if __name__ == '__main__':
    sys.exit(main())
