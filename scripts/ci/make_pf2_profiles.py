"""The tp4/prefill-2 gate-only twins of the approved ship-4 profile: the device-side hand-off of the final step's GDN state (QWEN_FAST_PREFILL_HANDOFF, docs/tp4-prefill-2.md), generated from
the files they are made of (stdlib only).

    python3 scripts/ci/make_pf2_profiles.py --write   regenerate the twins in scripts/ci/qwen_c2_profiles.json
    python3 scripts/ci/make_pf2_profiles.py --check   exit 1 if the checked-in twins are not what their parents generate

NEVER hand-merge these entries into the profiles file. Run make_fusion_profiles.py --write, make_octo3_profiles.py --write and make_ship4_profiles.py --write FIRST (the audit twin copies the
ship-4 audited twin, the other two the ship candidate), then this.

THE PROBLEM THEY SERVE. The last step of every prompt pays a host round trip of the GDN scratch before the decode slot is written: 240 blocking reads, 240 uploads, 48 layers of slot writes
(PF1 profile, run 38051000905: 48.6 ms of device idle for the reads and 115.2 ms for the writes, 8.0 ms of it device kernels). QWEN_FAST_PREFILL_HANDOFF=1 writes the slot from device-side clones of
the scratch instead (prefill_handoff.py). The approved traffic profile is NOT changed: the flag is not in it, and a traffic profile that wants it needs an owner traffic waiver that names it.

  -pf2-s4-ctl     THE CONTROL OF THE TIMED PAIR: the ship candidate (-fx-traffic-s4) with the gate marker instead of its owner waiver id and exactly QWEN_FAST_PREFILL_HANDOFF=0: the host path, byte for
                  byte the approved profile's, which also prints the '[PF2] handoff mode=host' timing line so that both arms of the pair print the quantity the lever changes.
  -pf2-s4         THE TIMED ARM: the same with QWEN_FAST_PREFILL_HANDOFF=1.
  -pf2-s4-audit   THE AUDITED ATTACH ARM: the ship-4 audited twin (every audit of the candidate, the tier's instruments) plus QWEN_FAST_PREFILL_HANDOFF=1 and QWEN_FAST_PREFILL_HANDOFF_AUDIT=1: the
                  first 8 final steps and every 24th read the whole decode state before and after the write and require the slot equal to the scratch and every other row unchanged.

All three are gate_only and unqualified. Nothing about the engine, the memory plan or any other flag differs from the parent. The names are outside the fusion generator's namespace on purpose
(make_fusion_profiles.py leaves them where they are); the twins sit right after the last -fx-s4-* profile, where the region-read twins (which own the end of the file) and the fusion block (which owns
the place before them) leave them alone.
"""

import argparse
import copy
import json
from pathlib import Path
import sys

import make_octo_profiles
import make_ship4_profiles as ship4

PROFILES = Path(__file__).resolve().parent / 'qwen_c2_profiles.json'

PREFIX = 'c2-packed-tp4-8x262k-ship-prefix-levern-w2-er-pf2-'
SHIP = ship4.SHIP
AUDIT_PARENT = ship4.AUDIT
CONTROL = PREFIX + 's4-ctl'
ARM = PREFIX + 's4'
AUDIT = PREFIX + 's4-audit'
FLAG = 'QWEN_FAST_PREFILL_HANDOFF'
AUDIT_FLAG = 'QWEN_FAST_PREFILL_HANDOFF_AUDIT'
WAIVER_ENV = ship4.WAIVER_ENV
WAIVER_FIELD = ship4.WAIVER_FIELD
MARKER_ENV = dict(make_octo_profiles.MARKER_ENV)
NAMES = (CONTROL, ARM, AUDIT)
MAX_NAME = 64


def control_description():
    return ('GATE ONLY, UNQUALIFIED (tp4/prefill-2, docs/tp4-prefill-2.md; never traffic). THE CONTROL of the device-side hand-off pair: the approved ship-4 profile %s with the gate marker %s instead '
            'of its owner waiver id %s and exactly %s=0 (the host path of the final step, unchanged; the route also prints its \'[PF2] handoff mode=host\' timing line, so both arms of the pair print '
            'the quantity the lever changes). Its engine, memory plan and every other flag are the parent\'s byte for byte. Generated by scripts/ci/make_pf2_profiles.py: regenerate, never hand-merge.'
            % (SHIP, ', '.join('%s=%s' % pair for pair in sorted(MARKER_ENV.items())), WAIVER_ENV, FLAG))


def arm_description():
    return ('GATE ONLY, UNQUALIFIED (tp4/prefill-2, docs/tp4-prefill-2.md; never traffic). THE TIMED ARM of the device-side hand-off: the approved ship-4 profile %s with the gate marker instead of its '
            'owner waiver id and exactly %s=1: the last step of every split prompt writes the decode slot from device-side clones of the GDN scratch (prefill_handoff.py) instead of a host round '
            'trip (240 reads, 240 uploads). The parent is %s and this profile is the control %s with the flag turned on and nothing else. Generated by scripts/ci/make_pf2_profiles.py: regenerate, '
            'never hand-merge.' % (SHIP, FLAG, SHIP, CONTROL))


def audit_description():
    return ('GATE ONLY, UNQUALIFIED (tp4/prefill-2, docs/tp4-prefill-2.md; never traffic, never a timed arm). THE AUDITED ATTACH ARM of the device-side hand-off: the ship-4 audited twin %s (every audit '
            'of the candidate, the host tier\'s instruments, the host read-backs sampled) plus exactly %s=1 and %s=1: the first 8 final steps and then every 24th read the whole batched decode '
            'state before and after the write and require the slot\'s rows equal to the scratch on every chip and every other row unchanged (\'[PINDIAG] prefill handoff audit n=.. exact=True\'). '
            'Generated by scripts/ci/make_pf2_profiles.py: regenerate, never hand-merge.' % (AUDIT_PARENT, FLAG, AUDIT_FLAG))


def twin_names():
    """The generated twins' names (the profile-enumerating tests exempt them through profile_twins; test_pf2_profiles holds each)."""
    return NAMES


def parent_problems(name, profile, audit):
    """Why `name` cannot be twinned, [] when it can."""
    problems = []
    env = profile.get('env') or {}
    for flag in (FLAG, AUDIT_FLAG):
        if flag in env:
            problems.append('%s already names %s: a parent never carries the knob it is twinned with' % (name, flag))
    if audit:
        if profile.get('gate_only') is not True or env.get('QWEN_C2_GATE_PROFILE') != '1':
            problems.append('%s is not the gate-only audited twin of the ship candidate' % name)
    else:
        waiver = profile.get(WAIVER_FIELD)
        if profile.get('gate_only') is True or not isinstance(waiver, dict):
            problems.append('%s is not a traffic profile with an owner traffic waiver: the arm is that profile with the gate marker in its place' % name)
        elif env.get(WAIVER_ENV) != waiver.get('id'):
            problems.append('%s does not carry its waiver id in %s' % (name, WAIVER_ENV))
        for flag in MARKER_ENV:
            if flag in env:
                problems.append('%s already names %s: a traffic profile never carries the gate marker' % (name, flag))
    if env.get('QWEN_FAST_LEVER_N') != '1':
        problems.append('%s does not run Lever N (QWEN_FAST_LEVER_N=1): the hand-off is a lever of its route' % name)
    return problems


def traffic_twin(profile, value, description):
    twin = copy.deepcopy(profile)
    twin['env'].pop(WAIVER_ENV)
    twin['env'].update(MARKER_ENV)
    twin['env'][FLAG] = value
    twin['description'] = description
    twin.pop(WAIVER_FIELD, None)
    twin.pop('gate_only', None)
    twin['gate_only'] = True
    return twin


def generate(data):
    """data's profiles with the twins written after every other entry (a previous generation is replaced; nothing else moves); returns the new dict."""
    profiles = data['profiles']
    for name in (AUDIT_PARENT, SHIP):
        if name not in profiles:
            raise ValueError('the parent profile %s is not defined (make_fusion_profiles.py --write, make_octo3_profiles.py --write and make_ship4_profiles.py --write, first)' % name)
    problems = parent_problems(AUDIT_PARENT, profiles[AUDIT_PARENT], True) + parent_problems(SHIP, profiles[SHIP], False)
    problems += ['%s is %d characters, over the %d a profile name may have' % (name, len(name), MAX_NAME) for name in NAMES if len(name) > MAX_NAME]
    if problems:
        raise ValueError('; '.join(problems))
    audit = copy.deepcopy(profiles[AUDIT_PARENT])
    audit['env'][FLAG] = '1'
    audit['env'][AUDIT_FLAG] = '1'
    audit['description'] = audit_description()
    audit.pop('gate_only', None)
    audit['gate_only'] = True
    generated = {CONTROL: traffic_twin(profiles[SHIP], '0', control_description()), ARM: traffic_twin(profiles[SHIP], '1', arm_description()), AUDIT: audit}
    remaining = [name for name in profiles if name not in generated]            # a previous generation is replaced below
    anchors = [name for name in remaining if name.startswith(ship4.NAMESPACE + 's4-')]
    if not anchors:
        raise ValueError('the tp4/ship-4 twins are not in the profiles file (make_ship4_profiles.py --write first)')
    anchor = anchors[-1]            # the last of the -fx-s4-* block (tp4/ship-4's twins, and any later package's twins of the same parent), so the generators commute
    result = {}
    for name in remaining:
        result[name] = profiles[name]
        if name == anchor:
            result.update(generated)
    out = dict(data)
    out['profiles'] = result
    return out


def render(data):
    return json.dumps(data, indent=2) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--path', default=str(PROFILES))
    arguments = parser.parse_args(argv)
    path = Path(arguments.path)
    current = path.read_text(encoding='utf-8')
    wanted = render(generate(json.loads(current)))
    if arguments.check:
        if wanted != current:
            sys.stderr.write('%s is not what make_pf2_profiles.py generates from its parents: run it with --write\n' % path)
            return 1
        return 0
    if arguments.write:
        if wanted != current:
            with open(str(path), 'w', encoding='utf-8', newline='\n') as handle:
                handle.write(wanted)
        return 0
    parser.error('--write or --check')


if __name__ == '__main__':
    sys.exit(main())
