"""The tp4/round-breakdown profile twins (round_probe, QWEN_FAST_TP4_ROUND_PROBE), generated from their parent (stdlib only).

    python3 scripts/ci/make_probe_profiles.py --write   regenerate the twins in scripts/ci/qwen_c2_profiles.json
    python3 scripts/ci/make_probe_profiles.py --check   exit 1 if the checked-in twins are not what their parent generates

NEVER hand-merge these entries into the profiles file. After a merge that moves the parent (the ship-5 candidate, written by make_fusion_profiles.py from fusion-wp/S5.json), run the
generators of the chain in their order and then this one: each twin is the parent's env, engine and every other field byte for byte plus exactly the env named below, and gate_only.

THE TWINS (suffixes of the ship-5 candidate's `-fx-` name):
  -s5-probe         the candidate with the round probe on. The candidate already writes the per-round ledger line (QWEN_FAST_TP4_ROUND_HOST_LEAN turns the ledger on) and the [OCTO] round
                    line, so the probe adds ONE line a probe round ([ROUND-PROBE]) and nothing else: every EVERY-th round waits for the queue twice (before the draft launches and before
                    the verify's pre-stage window) and the other rounds are the candidate's. Read PAIRED per round against the candidate's own log, probe rounds dropped (round_probe_report).
  -s5-probe-quads   the same without the octo draft pass (QWEN_FAST_OCTO_DRAFT unset, as octo-3's `-quaddraft` twin is): the fused quad drafters draft an octo round, cut to seven rows on
                    the host. The target's greedy text is the same in both arms, so the two logs are paired round for round by position and the acceptance of the two drafters is read at
                    identical positions (the one comparison the s5 logs cannot make: tau moves with the output position by more than the drafters differ).
Both are gate_only and unqualified: they serve no traffic, and the production profile and every non-gate profile carry no QWEN_FAST_TP4_ROUND_PROBE name (test_round_probe holds it).
"""

import argparse
import copy
import json
from pathlib import Path
import sys

PROFILES = Path(__file__).resolve().parent / 'qwen_c2_profiles.json'

# These names are make_s5_profiles' (SHIP and AUDIT_NOWC; test_round_probe holds that they are): literals, so that this module needs no import of it.
PARENT = 'c2-packed-tp4-8x262k-ship-prefix-levern-w2-er-fx-traffic-s5'
# Placed right after the ship-5 audited twins: make_s5_profiles owns those and make_fusion_profiles keeps them in place, so no other generator moves these entries (the traffic profile
# itself is rewritten by make_fusion_profiles into the block it places before the file's closing twins, and a twin placed after it would end up in the wrong place).
ANCHOR = 'c2-packed-tp4-8x262k-ship-prefix-levern-w2-er-fx-s5-audit-nowc'
# Named UNDER the op-fusion namespace (`...-w2-er-fx-`, like the ship-5 audited twins): the profile-enumerating tests recognise the namespace by name, and make_fusion_profiles keeps
# an entry under it only when it is listed in its `owned` set, which names this module's twin_names() beside make_s5_profiles'.
NAME = 'c2-packed-tp4-8x262k-ship-prefix-levern-w2-er-fx-s5-probe'
NAME_QUADS = NAME + '-quads'
FLAG = 'QWEN_FAST_TP4_ROUND_PROBE'
EVERY_FLAG = 'QWEN_FAST_TP4_ROUND_PROBE_EVERY'
EVERY = '8'
FLAGS = (FLAG, EVERY_FLAG)
WAIVER_ENV = 'QWEN_FAST_OCTO_WAIVER'                  # the candidate's owner traffic waiver is the candidate's own: a gate-only twin carries neither the field nor the id
WAIVER_FIELD = 'owner_traffic_waiver'
GATE_ENV = 'QWEN_C2_GATE_PROFILE'                     # what every gate-only twin of the stack sets (the audited twins of ship 4 and 5 do)
OCTO_DRAFT = 'QWEN_FAST_OCTO_DRAFT'


def description(quads):
    base = ('GATE ONLY, UNQUALIFIED (tp4/round-breakdown; never traffic). The parent is %s, the ship-5 candidate, and this profile is the parent plus %s=1, %s=%s and the gate-only marker, less the '
            'owner traffic waiver (the parent\'s own)%s and nothing else: every %sth round of the drafts\' coordinator waits for the device queue twice (the commits the step left, then the drafts it '
            'launched, before the verify\'s pre-stage window) and writes one [ROUND-PROBE] line with the two waits. Host only: no kernel, trace, allocation or device command; the other rounds are '
            'the parent\'s. A probe round is longer than a round by up to the window\'s time and is never a round time: round_probe_report drops it.'
            % (PARENT, FLAG, EVERY_FLAG, EVERY,
               ' and %s (the fused quad drafters draft the octo rounds, cut to seven rows: the draft A/B of the octo block, paired by position with the other twin)' % OCTO_DRAFT if quads else '',
               EVERY))
    return base + ' Generated by scripts/ci/make_probe_profiles.py: regenerate, never hand-merge.'


def twin_names():
    """The generated twins' names (the profile-enumerating tests exempt them through profile_twins; test_round_probe holds each)."""
    return (NAME, NAME_QUADS)


def parent_problems(profile):
    """Why the parent cannot be twinned, [] when it can."""
    problems = []
    for flag in FLAGS:
        if flag in (profile.get('env') or {}):
            problems.append('%s already names %s: a parent never carries the instrument it is twinned with' % (PARENT, flag))
    if profile.get('gate_only') is True:
        problems.append('%s is gate_only: the parent is the traffic profile' % PARENT)
    if (profile.get('env') or {}).get(OCTO_DRAFT) != '1':
        problems.append('%s does not name %s=1: nothing for the quads twin to take out' % (PARENT, OCTO_DRAFT))
    return problems


def generate(data):
    """data's profiles with the twins inserted right after the ship-5 audited twins (every other entry unmoved, a previous generation replaced); returns the new dict."""
    profiles = data['profiles']
    if PARENT not in profiles:
        raise ValueError('the parent profile %s is not defined (make_fusion_profiles.py --write first)' % PARENT)
    problems = parent_problems(profiles[PARENT])
    if problems:
        raise ValueError('; '.join(problems))
    if ANCHOR not in profiles:
        raise ValueError('the anchor %s is not defined (make_s5_profiles.py --write first)' % ANCHOR)
    generated = {}
    for name, quads in ((NAME, False), (NAME_QUADS, True)):
        twin = copy.deepcopy(profiles[PARENT])
        twin['env'].update({FLAG: '1', EVERY_FLAG: EVERY, GATE_ENV: '1'})
        twin['env'].pop(WAIVER_ENV, None)
        if quads:
            twin['env'].pop(OCTO_DRAFT)
        twin['description'] = description(quads)
        twin.pop(WAIVER_FIELD, None)
        twin.pop('gate_only', None)
        twin['gate_only'] = True
        generated[name] = twin
    result = {}
    for key, profile in profiles.items():
        if key in generated:
            continue                                    # a previous generation: replaced below
        result[key] = profile
        if key == ANCHOR:
            result.update(generated)
    out = dict(data)
    out['profiles'] = result
    return out


def render(data):
    return json.dumps(data, indent=2) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--path', default=str(PROFILES))
    arguments = parser.parse_args(argv)
    path = Path(arguments.path)
    current = path.read_text(encoding='utf-8')
    wanted = render(generate(json.loads(current)))
    if arguments.check:
        if wanted != current:
            sys.stderr.write('%s is not what make_probe_profiles.py generates from its parent: run it with --write\n' % path)
            return 1
        return 0
    if arguments.write:
        if wanted != current:
            with open(str(path), 'w', encoding='utf-8', newline='\n') as handle:
                handle.write(wanted)
        return 0
    parser.error('--write or --check')


if __name__ == '__main__':
    sys.exit(main())
